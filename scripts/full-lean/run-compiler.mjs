// Execute the full Lean Wasm compiler inside this JavaScript process. There is
// intentionally no fallback to a native Lean executable when artifacts are absent.
import { existsSync, readFileSync, writeFileSync, renameSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));

const argv = process.argv.slice(2);
const option = argv.indexOf('--prefix');
let prefix = process.env.LASM_FULL_LEAN_PREFIX ?? join(root, '.work/lean-full/wasm');
if (option >= 0) {
  prefix = argv[option + 1];
  if (!prefix) throw new Error('--prefix needs a full compiler build directory');
  argv.splice(option, 2);
}
prefix = resolve(prefix);
const original = join(prefix, 'bin/lean.js');
if (!existsSync(original) || !existsSync(join(prefix, 'bin/lean.wasm')))
  throw new Error(`Full Lean Wasm compiler not built at ${prefix}; see scripts/full-lean/README.md`);
// Emscripten emits CommonJS as .js. A .cjs copy also works inside a type:module
// package and in Deno, while preserving the generated bytes and worker entry.
const executable = join(prefix, 'bin/lean.cjs');
const glue = readFileSync(original);
if (!existsSync(executable) || !readFileSync(executable).equals(glue)) {
  const temporary = `${executable}.${process.pid}.tmp`;
  writeFileSync(temporary, glue); renameSync(temporary, executable);
}
process.argv = [process.execPath, executable, ...argv];
const frozenHost = join(prefix, 'host/node-host.mjs');
process.env.LASM_FULL_HOST_MODULE = existsSync(frozenHost)
  ? pathToFileURL(frozenHost).href : new URL('../../src/node-host.mjs', import.meta.url).href;
createRequire(import.meta.url)(executable);
