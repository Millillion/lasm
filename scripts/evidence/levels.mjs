// Platform evidence levels L0–L3 (docs/TESTING.md#evidence-levels), derived from
// CI results and shown in the README's platform table.
//
//   node scripts/evidence/levels.mjs [--out RESULT.json] [--write | --check]
//
// Reads scripts/evidence/platforms.json (which jobs back which level for each
// platform), finds through the GitHub API the newest completed main-branch run
// (or release-* branch run) of each named workflow that has a non-skipped job
// matching each requirement, and computes each platform's level. --write
// rewrites only the region of README.md between the evidence-levels markers:
// the table's Evidence column and the legend line under it. Every other cell is
// kept as written. --check fails when that region differs from what the CI
// results give. Needs GITHUB_TOKEN or GH_TOKEN; GITHUB_REPOSITORY defaults to
// Millillion/lasm.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const START = '<!-- evidence-levels:start (generated by scripts/evidence/levels.mjs; edit the cells, not the How well tested column) -->';
export const END = '<!-- evidence-levels:end -->';
export const LEVELS = ['L0', 'L1', 'L2', 'L3'];
const DAY = 86_400_000;
const BRANCH = /^(main|release-.+)$/;

/**
 * Each requirement's result from `runs` ({ [workflow]: runs newest first }) and
 * `jobs` ({ [runId]: jobs }): the newest run with a non-skipped matching job decides.
 */
export function requirementResult(requirement, runs, jobs, now, maxAgeDays) {
  const pattern = new RegExp(requirement.job);
  for (const run of runs[requirement.workflow] ?? []) {
    const matching = (jobs[run.id] ?? []).filter(job => pattern.test(job.name) && job.conclusion !== 'skipped' && job.conclusion !== null);
    if (matching.length === 0) continue;
    const ageDays = Math.floor((now - Date.parse(run.updated_at ?? run.created_at)) / DAY);
    const failed = matching.filter(job => job.conclusion !== 'success');
    const ok = failed.length === 0 && ageDays <= maxAgeDays;
    return { ...requirement, ok, run: run.html_url, branch: run.head_branch, ageDays, jobs: matching.length,
      ...(failed.length ? { failed: failed.map(job => `${job.name}: ${job.conclusion}`) } : {}),
      ...(ageDays > maxAgeDays ? { stale: true } : {}) };
  }
  return { ...requirement, ok: false, missing: true };
}

/** { id, row, level (-1 when not even L0), levels: { L0: { ok, requirements } … } } per platform. */
export function evaluate(config, runs, jobs, now = Date.now()) {
  return config.platforms.map(platform => {
    const levels = {};
    let level = -1, open = true;
    for (const name of LEVELS) {
      const requirements = platform[name] === null ? null : platform[name].map(r => requirementResult(r, runs, jobs, now, config.maxAgeDays));
      const ok = requirements !== null && requirements.every(r => r.ok);
      levels[name] = { ok, ...(requirements === null ? { noEvidenceYet: true } : { requirements }) };
      if (open && ok) level = LEVELS.indexOf(name); else open = false;
    }
    return { id: platform.id, row: platform.row, level, levels };
  });
}

/** The README table's generated column. */
export const COLUMN = 'How well tested';

export const levelText = level => level < 0 ? '—' : LEVELS[level];

export function legend(config) {
  return `How well tested, generated from CI ([how](docs/TESTING.md#evidence-levels)): ${LEVELS.map(name => `**${name}** ${config.levels[name].charAt(0).toLowerCase() + config.levels[name].slice(1)}`).join('; ')}.`;
}

const cells = line => line.trim().replace(/^\|/, '').replace(/\|$/, '').split(/(?<!\\)\|/).map(cell => cell.trim());
const rowLine = values => `| ${values.join(' | ')} |`;

/** README.md with the marked region regenerated: the table's Evidence column and the legend. */
export function render(readme, results, config) {
  const start = readme.indexOf(START), end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error('README.md has no evidence-levels markers');
  const region = readme.slice(start + START.length, end);
  const lines = region.split('\n');
  const table = lines.filter(line => line.trim().startsWith('|'));
  if (table.length < 3) throw new Error('no table between the evidence-levels markers');
  const header = cells(table[0]);
  // 'Evidence' is the column's earlier name, replaced on the next --write.
  const hasColumn = [COLUMN, 'Evidence'].includes(header.at(-1));
  const width = hasColumn ? header.length - 1 : header.length;
  const used = new Set();
  const out = [rowLine([...header.slice(0, width), COLUMN]), rowLine(Array(width + 1).fill('---'))];
  for (const line of table.slice(2)) {
    const values = cells(line).slice(0, width);
    const result = results.find(r => values[0].startsWith(r.row));
    if (!result) throw new Error(`no platform in scripts/evidence/platforms.json for the README row "${values[0]}"`);
    used.add(result.id);
    out.push(rowLine([...values, levelText(result.level)]));
  }
  const unused = results.filter(r => !used.has(r.id)).map(r => r.row);
  if (unused.length) throw new Error(`README.md's platform table has no row for: ${unused.join(', ')}`);
  return readme.slice(0, start + START.length) + '\n' + out.join('\n') + '\n\n' + legend(config) + '\n' + readme.slice(end);
}

/** A GitHub REST GET for `repository` (JSON), retried on 5xx and 429. */
export function githubApi(repository, token, agent = 'lasm-evidence-levels') {
  return async path => {
    for (let attempt = 1; ; attempt++) {
      const response = await fetch(`https://api.github.com/repos/${repository}/${path}`, { headers: { Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github+json', 'User-Agent': agent }, signal: AbortSignal.timeout(60_000) });
      if (response.ok) return response.json();
      if (attempt < 4 && (response.status >= 500 || response.status === 429)) { await new Promise(done => setTimeout(done, 5000 * attempt)); continue; }
      throw new Error(`GET ${path}: HTTP ${response.status} ${(await response.text()).slice(0, 200)}`);
    }
  };
}

/** The runs and jobs `evaluate` needs, from the GitHub API. */
export async function collect(config, { repository, token, now, api = githubApi(repository, token) }) {
  const requirements = config.platforms.flatMap(p => LEVELS.flatMap(name => p[name] ?? []));
  const runs = {}, jobs = {};
  for (const workflow of [...new Set(requirements.map(r => r.workflow))]) {
    const patterns = requirements.filter(r => r.workflow === workflow).map(r => new RegExp(r.job));
    const pending = new Set(patterns);
    runs[workflow] = [];
    for (let page = 1; page <= 3 && pending.size; page++) {
      const batch = await api(`actions/workflows/${workflow}/runs?status=completed&per_page=100&page=${page}`);
      const candidates = batch.workflow_runs.filter(run => BRANCH.test(run.head_branch) && run.conclusion !== 'skipped'
        && now - Date.parse(run.created_at) <= (config.maxAgeDays + 30) * DAY);
      for (const run of candidates) {
        if (!pending.size) break;
        // Pages of 30: the API answers 502 for 100 jobs of a large run (release-checks).
        const list = [];
        try {
          for (let jobPage = 1; jobPage <= 10; jobPage++) {
            const response = await api(`actions/runs/${run.id}/jobs?filter=latest&per_page=30&page=${jobPage}`);
            list.push(...response.jobs);
            if (response.jobs.length < 30) break;
          }
        } catch (error) { console.warn(`::warning::jobs of ${run.html_url} unavailable (${String(error.message).slice(0, 120)}); using older runs`); continue; }
        jobs[run.id] = list;
        runs[workflow].push(run);
        for (const pattern of [...pending]) if (list.some(job => pattern.test(job.name) && job.conclusion && job.conclusion !== 'skipped')) pending.delete(pattern);
      }
      if (batch.workflow_runs.length < 100) break;
    }
  }
  return { runs, jobs };
}

async function main() {
  const argv = process.argv.slice(2);
  const config = JSON.parse(readFileSync(resolve(root, 'scripts/evidence/platforms.json'), 'utf8'));
  const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  if (!token) throw new Error('GITHUB_TOKEN or GH_TOKEN is required');
  const now = Date.now();
  const { runs, jobs } = await collect(config, { repository: process.env.GITHUB_REPOSITORY ?? 'Millillion/lasm', token, now });
  const results = evaluate(config, runs, jobs, now);
  for (const r of results) {
    console.log(`${levelText(r.level).padEnd(3)} ${r.row}`);
    for (const name of LEVELS) for (const req of r.levels[name].requirements ?? []) if (!req.ok)
      console.log(`      ${name} needs ${req.workflow} /${req.job}/: ${req.missing ? 'no main-branch run has this job' : req.stale ? `newest run is ${req.ageDays} days old` : (req.failed ?? []).join('; ')}`);
  }
  if (argv.includes('--out')) {
    const out = resolve(argv[argv.indexOf('--out') + 1]);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, JSON.stringify({ generatedAt: new Date(now).toISOString(), platforms: results }, null, 2) + '\n');
  }
  const readmePath = resolve(root, 'README.md');
  const readme = readFileSync(readmePath, 'utf8');
  const next = render(readme, results, config);
  if (argv.includes('--write')) { writeFileSync(readmePath, next); console.log(next === readme ? 'README.md unchanged' : 'README.md updated'); }
  if (argv.includes('--check') && next !== readme) {
    console.error('README.md\'s evidence levels differ from the latest CI results; run node scripts/evidence/levels.mjs --write');
    process.exit(1);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
