// Moves Lasm's version references from one Lean release to the next
// (docs/LEAN_UPGRADE.md step 2). Mechanical rewrites only; per-release data that
// must be produced again (runtime and edge pins, upstream-suite reviews, the
// initializer list, the prebuilt library, tiers) is left to the later steps,
// which this script lists at the end.
//   node scripts/lean-upgrade/bump.mjs FROM TO [--dry-run]
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const [from, to, ...rest] = process.argv.slice(2);
const dry = rest.includes('--dry-run');
const release = /^\d+\.\d+\.\d+(-rc\d+)?$/;
assert.ok(release.test(from ?? '') && release.test(to ?? ''), 'Usage: node scripts/lean-upgrade/bump.mjs FROM TO [--dry-run]');
const root = fileURLToPath(new URL('../../', import.meta.url));
const files = execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' }).trim().split('\n');
const esc = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const F = esc(from);
// Code, configuration and fixtures; never docs, evidence or recorded history.
const code = name => /^(?:src|scripts|templates|test|integration|examples|bench|experiments|\.github)\//.test(name)
  && !/(?:^|\/)(?:evidence|history)\//.test(name) && /\.(?:mjs|cjs|js|json|yml|yaml|lean|toml|sh|py)$|(?:^|\/)lean-toolchain$/.test(name);
// Per-release data, regenerated by later steps rather than renamed.
const perRelease = name => /(?:-reviewed|runtime-adapter-l\d+|lean-init-targets-[^/]*|c-tier-sources|source-archives|toolchains|lean-sources|application-runtimes|edge-runtimes|node-runtime-source|baseline)\.json$|lean-\d+\.\d+\.\d+[^/]*-upstream\.json$|^library\/prebuilt\//.test(name);
const rules = [
  ['lean-toolchain pins', name => /(?:^|\/)lean-toolchain$/.test(name), text => text.replaceAll(`v${from}`, `v${to}`)],
  ['leanprover/lean4:v<from>', code, text => text.replaceAll(`leanprover/lean4:v${from}`, `leanprover/lean4:v${to}`)],
  ['runtime archive names', name => code(name) && !perRelease(name), text => text.replace(new RegExp(`lean-${F}-wasm64`, 'g'), `lean-${to}-wasm64`)],
  ['catalog lookups', name => code(name) && !perRelease(name), text => text.replace(new RegExp(`\\.lean\\[(['"])${F}\\1\\]`, 'g'), `.lean[$1${to}$1]`)],
  ['workflow input defaults', name => name.startsWith('.github/workflows/'), text => text.replace(new RegExp(`(\\n\\s+default: )${F}(\\s*\\n)`, 'g'), `$1${to}$2`)
    .replace(new RegExp(`(default: lean-)${F}(-tiers-v)\\d+`, 'g'), `$1${to}$2` + '1')],
  ['script default versions', name => code(name) && /\.mjs$/.test(name), text => text.replace(new RegExp(`(version = )(['"])${F}\\2`, 'g'), `$1$2${to}$2`)],
  ['version allow-lists', name => code(name) && /\.mjs$/.test(name) && !perRelease(name),
    text => text.replace(new RegExp(`(\\[(?:'\\d+\\.\\d+\\.\\d+(?:-rc\\d+)?', )*'${F}')\\]`, 'g'), `$1, '${to}']`)],
];
const changed = {};
for (const name of files) {
  let text;
  try { text = readFileSync(`${root}${name}`, 'utf8'); } catch { continue; }
  let next = text;
  for (const [label, applies, rewrite] of rules) if (applies(name)) {
    const after = rewrite(next);
    if (after !== next) (changed[label] ??= []).push(name);
    next = after;
  }
  if (next !== text && !dry) writeFileSync(`${root}${name}`, next);
}
for (const [label, names] of Object.entries(changed)) console.log(`${label}: ${names.length} files\n  ${names.join('\n  ')}`);
const left = execFileSync('git', ['grep', '-l', '-F', from, '--', ':!docs', ':!**/evidence/**', ':!**/history/**'], { cwd: root, encoding: 'utf8' }).trim();
console.log(`\nStill naming ${from} (per-release data and comments; see docs/LEAN_UPGRADE.md steps 3-8):\n${left.split('\n').map(l => '  ' + l).join('\n')}`);
