// The last step of `lasm build --target browser` (docs/deploy/browser.md):
// checks the written output against its lasm-manifest.json (every file present
// with its digest, the precompressed copies decompressing to it) and adds the
// host configuration file static hosts read: `_headers` (Netlify, Cloudflare
// Pages) with immutable caching of the content-hashed files and the Wasm MIME
// type. Files only, no network.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { writeFileIfChanged } from '../output-directory.mjs';
import { join, resolve, relative } from 'node:path';
import { brotliDecompressSync, gunzipSync } from 'node:zlib';

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const generatedHeaders = '# Generated by Lasm';

/** Whether `path` is a _headers file Lasm wrote (not one from the project's public/). */
export function isGeneratedHeaders(path) {
  try { return readFileSync(path, 'utf8').startsWith(generatedHeaders); } catch { return false; }
}

export function headersFile(manifest) {
  const lines = [`${generatedHeaders} (lasm build --target browser): caching and types for Netlify and Cloudflare Pages.`];
  for (const file of [manifest.entry, manifest.wasm])
    lines.push(`/${file}`, '  Cache-Control: public, max-age=31536000, immutable', ...(file.endsWith('.wasm') ? ['  Content-Type: application/wasm'] : []));
  for (const file of [manifest.index, manifest.stableEntry, 'lasm-manifest.json']) lines.push(`/${file}`, '  Cache-Control: no-cache');
  return lines.join('\n') + '\n';
}

/** Checks the browser output `input` against `manifest` (what lasm build just wrote) and writes _headers. */
export function checkBrowserOutput({ input, manifest, log = console.error }) {
  const directory = resolve(input);
  for (const [file, info] of Object.entries(manifest.files)) {
    const path = join(directory, file);
    if (!existsSync(path)) throw new Error(`${relative(process.cwd(), path)} is missing`);
    const bytes = readFileSync(path);
    if (sha256(bytes) !== info.sha256) throw new Error(`${file} does not match lasm-manifest.json (its SHA-256 differs)`);
    for (const [suffix, decode] of [['.br', brotliDecompressSync], ['.gz', gunzipSync]]) {
      if (info[suffix === '.br' ? 'brotli' : 'gzip'] === undefined) continue;
      if (!existsSync(path + suffix) || sha256(decode(readFileSync(path + suffix))) !== info.sha256) throw new Error(`${file}${suffix} is missing or does not match ${file}`);
    }
  }
  const headers = join(directory, '_headers');
  if (existsSync(headers) && !isGeneratedHeaders(headers)) log(`[lasm] Kept your ${relative(process.cwd(), headers)}`);
  else writeFileIfChanged(headers, headersFile(manifest));
}
