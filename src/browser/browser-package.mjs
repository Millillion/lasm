// `lasm package [dist] --target browser` (docs/deploy/browser.md): checks a
// browser build against its lasm-manifest.json (every file present with its
// digest, the precompressed copies decompressing to it) and adds the host
// configuration files static hosts read: `_headers` (Netlify, Cloudflare Pages)
// with immutable caching of the content-hashed files and the Wasm MIME type.
// Files only, no network.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, relative } from 'node:path';
import { brotliDecompressSync, gunzipSync } from 'node:zlib';

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

export function headersFile(manifest) {
  const lines = ['# Generated by Lasm (lasm package --target browser): caching and types for Netlify and Cloudflare Pages.'];
  for (const file of [manifest.entry, manifest.wasm])
    lines.push(`/${file}`, '  Cache-Control: public, max-age=31536000, immutable', ...(file.endsWith('.wasm') ? ['  Content-Type: application/wasm'] : []));
  for (const file of [manifest.index, manifest.stableEntry, 'lasm-manifest.json']) lines.push(`/${file}`, '  Cache-Control: no-cache');
  return lines.join('\n') + '\n';
}

export function packageBrowser({ input = 'dist', log = console.error } = {}) {
  const directory = resolve(input);
  const manifestFile = join(directory, 'lasm-manifest.json');
  if (!existsSync(manifestFile)) throw new Error(`${input} is not a browser build (no lasm-manifest.json); run lasm build Main.lean --target browser first`);
  const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'));
  if (manifest.target !== 'browser' || manifest.schema !== 1) throw new Error(`${manifestFile} is not a Lasm browser manifest`);
  for (const [file, info] of Object.entries(manifest.files)) {
    const path = join(directory, file);
    if (!existsSync(path)) throw new Error(`${relative(process.cwd(), path)} is missing`);
    const bytes = readFileSync(path);
    if (sha256(bytes) !== info.sha256) throw new Error(`${file} changed since lasm build (its SHA-256 differs from lasm-manifest.json)`);
    for (const [suffix, decode] of [['.br', brotliDecompressSync], ['.gz', gunzipSync]]) {
      if (info[suffix === '.br' ? 'brotli' : 'gzip'] === undefined) continue;
      if (!existsSync(path + suffix) || sha256(decode(readFileSync(path + suffix))) !== info.sha256) throw new Error(`${file}${suffix} is missing or does not match ${file}`);
    }
  }
  const headers = join(directory, '_headers');
  if (existsSync(headers) && !readFileSync(headers, 'utf8').startsWith('# Generated by Lasm')) log(`[lasm] Kept your ${relative(process.cwd(), headers)}`);
  else writeFileSync(headers, headersFile(manifest));
  log(`Checked ${Object.keys(manifest.files).length} files of ${relative(process.cwd(), directory) || directory} (${(manifest.transfer.brotli / 1024).toFixed(1)} KiB brotli); wrote _headers. Upload the directory to any static host: docs/deploy/browser.md`);
  return 0;
}
