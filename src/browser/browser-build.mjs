// `lasm build --target browser` (docs/BROWSER.md): the edge program (the Node
// build's objects relinked single-threaded, src/edge/edge-link.mjs; the same
// cached link as the edge targets) delivered as a static web app:
//   app.<hash>.js     the loader, bundled with the glue, the host and the builtin
//                     modules (src/browser/loader.mjs, bundle.mjs)
//   app.<hash>.wasm   the program
//   *.br, *.gz        precompressed copies of both
//   app.js            a stable name that re-exports app.<hash>.js (short caching)
//   index.html        the project's index.html with the loader injected, or a
//                     generated page when the project has none
//   public/**         the project's public/ files, copied as they are
//   lasm-manifest.json  file names, sizes, digests and transfer totals
import { mkdirSync, readFileSync, writeFileSync, copyFileSync, existsSync, rmSync, renameSync, readdirSync, statSync, cpSync } from 'node:fs';
import { basename, join, relative, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { brotliCompressSync, gzipSync, constants as zlib } from 'node:zlib';
import { bundleModules, compactModule, emscriptenModule } from './bundle.mjs';
import { builtinModuleClosure, builtinModuleFile, builtinPrefix } from '../edge/builtin-modules.mjs';
import { edgeModules } from '../edge/edge-build.mjs';

const here = fileURLToPath(new URL('./', import.meta.url));
const edge = fileURLToPath(new URL('../edge/', import.meta.url));
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const shortHash = bytes => sha256(bytes).slice(0, 12);
export const browserSuspendModes = Object.freeze(['none', 'jspi']);
const generatedMarker = 'Generated by Lasm (lasm build --target browser)';

/** The app's name: package.json's name, else the directory's; used by auto-mount (data-lasm-app="name"). */
export function browserAppName(projectDirectory) {
  const file = join(projectDirectory, 'package.json');
  let name;
  try { name = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')).name : undefined; } catch { /* not JSON: the directory name */ }
  return String(name ?? basename(projectDirectory)).replace(/^@[^/]+\//, '').replace(/[^A-Za-z0-9._-]+/g, '-') || 'lasm-app';
}

/** The generated configuration module the loader imports (src/browser/loader.mjs). */
export function browserConfigModule({ name, wasmFile, modules, suspend, autoMount = true }) {
  const source = specifier => specifier.startsWith(builtinPrefix) ? `./modules/${specifier.slice(builtinPrefix.length)}.mjs` : specifier;
  const imports = modules.map((specifier, i) => `import * as m${i} from ${JSON.stringify(source(specifier))};`);
  return [...imports,
    `export const name = ${JSON.stringify(name)};`,
    // new URL(<literal>, import.meta.url): bundlers (Vite, esbuild, webpack) recognize it as an asset.
    `export const wasmUrl = () => new URL(${JSON.stringify('./' + wasmFile)}, import.meta.url);`,
    `export const modules = { ${modules.map((specifier, i) => `${JSON.stringify(specifier)}: m${i}`).join(', ')} };`,
    `export const suspend = ${JSON.stringify(suspend)};`,
    `export const autoMount = ${autoMount ? 'true' : 'false'};`].join('\n') + '\n';
}

/** The loader bundle's text for a program (its glue program.mjs) and builtin modules. */
export function browserBundle({ programGlue, name, wasmFile, modules, suspend, autoMount = true, compact = true }) {
  const builtins = builtinModuleClosure(modules);
  const external = modules.filter(m => !m.startsWith(builtinPrefix));
  const read = file => { const text = readFileSync(file, 'utf8'); return compact ? compactModule(text) : text; };
  const sources = {
    './loader.mjs': read(join(here, 'loader.mjs')),
    './config.mjs': browserConfigModule({ name, wasmFile, modules, suspend, autoMount }),
    // The glue's own Wasm location is never used (the loader instantiates the
    // module itself); as a plain string bundlers do not look for the file.
    './program.mjs': emscriptenModule(programGlue.replace(/new URL\("program\.wasm",\s*import\.meta\.url\)/g, '"program.wasm"')),
    './edge-start.mjs': read(join(edge, 'edge-start.mjs')),
    './edge-host.mjs': read(join(edge, 'edge-host.mjs')),
    './edge-js.mjs': read(join(edge, 'edge-js.mjs')),
  };
  for (const specifier of builtins) sources[`./modules/${specifier.slice(builtinPrefix.length)}.mjs`] = read(builtinModuleFile(specifier));
  return bundleModules(sources, './loader.mjs', { header: `// ${generatedMarker}: the ${name} app's loader, Lean runtime host and program glue. Do not edit.`,
    external: specifier => external.includes(specifier) });
}

const brotli = bytes => brotliCompressSync(bytes, { params: { [zlib.BROTLI_PARAM_QUALITY]: 11, [zlib.BROTLI_PARAM_SIZE_HINT]: bytes.length,
  [zlib.BROTLI_PARAM_LGWIN]: 24, [zlib.BROTLI_PARAM_MODE]: zlib.BROTLI_MODE_GENERIC } });
const gzip = bytes => gzipSync(bytes, { level: 9 });

const escapeHtml = text => String(text).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
/** The tags that load the app: preload hints for both files, and the module script. */
export function headTags({ entry, wasm }) {
  return [`<link rel="modulepreload" href="./${entry}">`,
    `<link rel="preload" href="./${wasm}" as="fetch" type="application/wasm" crossorigin>`,
    `<script type="module" src="./${entry}"></script>`].join('\n    ');
}
export function defaultIndexHtml({ name, entry, wasm }) {
  return `<!doctype html>
<!-- ${generatedMarker}: the project has no index.html. Add one to customize the page; the loader is injected before </head>. -->
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>${escapeHtml(name)}</title>
    ${headTags({ entry, wasm })}
  </head>
  <body>
    <div id="app" data-lasm-app></div>
    <noscript>This app needs JavaScript and WebAssembly.</noscript>
  </body>
</html>
`;
}
/** The project's index.html with the loader's tags before </head>. */
export function injectIndexHtml(html, { entry, wasm }) {
  if (/<script[^>]+src=["'][^"']*app\.[0-9a-f]{12}\.js["']/i.test(html)) throw new Error('index.html already loads a hashed Lasm loader; remove that script: lasm build injects it');
  const tags = `    <!-- ${generatedMarker} -->\n    ${headTags({ entry, wasm })}\n  `;
  const at = html.search(/<\/head\s*>/i);
  if (at < 0) throw new Error('index.html has no </head>: Lasm injects the loader there');
  return html.slice(0, at) + tags + html.slice(at);
}

/** Writes the browser output; returns { output, manifest }. */
/** externals: 'error' (a static build: only Lasm's builtin modules and URL
 * modules), or 'keep' (a bundler such as Vite resolves npm imports). */
export function writeBrowserOutput({ source, projectDirectory, result, program, output, suspend = 'none', log = console.error, cacheHit = false, lasmVersion, externals = 'error' }) {
  if (!browserSuspendModes.includes(suspend)) throw new Error(`--suspend must be one of ${browserSuspendModes.join(', ')}`);
  if (program.meta.suspend !== 'jspi') throw new Error('The browser build uses the JSPI-linked edge program (internal error)');
  const destination = resolve(output ?? join(projectDirectory, 'dist'));
  if (destination === resolve(projectDirectory) || !relative(destination, source).startsWith('..'))
    throw new Error('The browser output directory must not contain the Lean sources');
  if (existsSync(destination) && readdirSync(destination).length) {
    let owned = false;
    try { owned = JSON.parse(readFileSync(join(destination, 'lasm-manifest.json'), 'utf8')).target === 'browser'; } catch { /* not ours */ }
    if (!owned) throw new Error(`${destination} exists and is not a Lasm browser build; remove it, or choose another --output`);
  }
  const name = browserAppName(projectDirectory);
  const wasmBytes = readFileSync(join(program.directory, 'program.wasm'));
  const wasm = `app.${shortHash(wasmBytes)}.wasm`;
  // The modules of the program's bindings and package.json's lasm.edge.modules;
  // lasm:app is present in every browser app (mount's ports and messages).
  const builtins = [...new Set([...edgeModules(projectDirectory, result.jsBindings ?? []), 'lasm:app'])].sort();
  const bare = builtins.filter(m => !m.startsWith(builtinPrefix) && !/^https?:\/\//.test(m));
  if (bare.length && externals !== 'keep')
    throw new Error(`The program uses npm modules (${bare.join(', ')}), which a static browser build cannot resolve. Build it with Vite and the CLI's plugin, @lasm/cli/vite (it bundles npm packages), or bind a URL module (@[js "https://…" …]).`);
  const bundle = Buffer.from(browserBundle({ programGlue: readFileSync(join(program.directory, 'program.mjs'), 'utf8'), name, wasmFile: wasm, modules: builtins, suspend }));
  const entry = `app.${shortHash(bundle)}.js`;
  const staging = destination + '.lasm-staging';
  rmSync(staging, { recursive: true, force: true });
  mkdirSync(staging, { recursive: true });
  // public/: copied first, so Lasm's own files win.
  const publicDirectory = join(projectDirectory, 'public');
  if (existsSync(publicDirectory) && statSync(publicDirectory).isDirectory()) {
    if (!relative(publicDirectory, destination).startsWith('..')) throw new Error('The browser output directory must not be inside public/');
    cpSync(publicDirectory, staging, { recursive: true });
  }
  const files = {};
  const emit = (file, bytes, { compress = false } = {}) => {
    writeFileSync(join(staging, file), bytes);
    files[file] = { bytes: bytes.length, sha256: sha256(bytes) };
    if (compress) {
      const br = brotli(bytes), gz = gzip(bytes);
      writeFileSync(join(staging, file + '.br'), br);
      writeFileSync(join(staging, file + '.gz'), gz);
      Object.assign(files[file], { brotli: br.length, gzip: gz.length });
    }
  };
  emit(wasm, wasmBytes, { compress: true });
  emit(entry, bundle, { compress: true });
  emit('app.js', Buffer.from(`// ${generatedMarker}: a stable name for ${entry}; serve it with a short cache lifetime.\nexport * from './${entry}';\nexport { default } from './${entry}';\n`));
  const projectIndex = join(projectDirectory, 'index.html');
  const html = existsSync(projectIndex) ? injectIndexHtml(readFileSync(projectIndex, 'utf8'), { entry, wasm }) : defaultIndexHtml({ name, entry, wasm });
  emit('index.html', Buffer.from(html), { compress: true });
  copyFileSync(join(result.output, 'THIRD_PARTY_NOTICES.txt'), join(staging, 'THIRD_PARTY_NOTICES.txt'));
  const transfer = { brotli: files[wasm].brotli + files[entry].brotli, gzip: files[wasm].gzip + files[entry].gzip,
    uncompressed: files[wasm].bytes + files[entry].bytes };
  const manifest = { schema: 1, generator: 'lasm', target: 'browser', name, lasm: lasmVersion ?? null, lean: result.lean,
    entry, wasm, stableEntry: 'app.js', index: 'index.html', suspend, modules: builtins,
    // Content-hashed files are immutable; the others change with every build.
    immutable: [entry, wasm, ...[entry, wasm].flatMap(file => [file + '.br', file + '.gz'])],
    transfer, files, programKey: program.meta.key, nodeBuildSignature: result.signature };
  writeFileSync(join(staging, 'lasm-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  rmSync(destination, { recursive: true, force: true });
  mkdirSync(dirname(destination), { recursive: true });
  renameSync(staging, destination);
  const kib = n => (n / 1024).toFixed(1) + ' KiB';
  log(`${cacheHit ? 'Reused' : 'Built'} ${relative(process.cwd(), source) || source} for the browser: ${relative(process.cwd(), destination) || destination}`
    + ` (${entry} + ${wasm}: ${kib(transfer.brotli)} brotli, ${kib(transfer.gzip)} gzip, ${kib(transfer.uncompressed)} uncompressed)`);
  return { output: destination, manifest };
}
