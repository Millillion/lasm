// Lasm's library as a Lake package, for Lake projects (docs/api/decisions/0.3.md, 0.3-7; docs/HOW_LASM_WORKS.md,
// "Lasm's library in Lake projects"). A project's lakefile requires it:
//
//   [[require]]
//   name = "lasm"
//   path = ".lake/lasm-library"
//
// `.lake/lasm-library` is a link (a junction on Windows) that every lasm command creates or repairs. It points to
// one package per Lean prefix and Lasm library in Lasm's cache: a lakefile whose one library has as roots the modules
// compiled on first import (src/lazy-library.mjs), with the sources of the installed Lasm library. Lake then builds
// those modules on demand, in `lake build` and in the editor (`lake setup-file`), like any dependency.
//
// The modules compiled with the prefix (libraryModules) are not Lake's: Lean takes the package `Lasm` from the first
// LEAN_PATH directory that has `Lasm/`, which is this package's build directory, so their .olean files are linked
// into it (hard links, or copies where the file system has none). A receipt records what was linked for which
// prefix and library; a missing, changed or stale link (an older Lasm, another prefix) is replaced.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, linkSync, lstatSync, mkdirSync, readFileSync, readlinkSync, realpathSync, renameSync, rmSync, statSync,
  symlinkSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { lazyModules, libraryRoot } from './lazy-library.mjs';
import { managedCacheDirectory } from './managed-artifacts.mjs';

/** The package's name, and the project path its link has. */
export const lakePackageName = 'lasm';
export const lakeLinkPath = project => join(project, '.lake', 'lasm-library');
/** The lakefile.toml lines a project adds (lasm init writes them; lasm editor adds them). */
export const lakeRequireToml = `[[require]]\nname = "${lakePackageName}"\npath = ".lake/lasm-library"\n`;
/** The same for a lakefile.lean. */
export const lakeRequireLean = `require ${lakePackageName} from ".lake" / "lasm-library"\n`;

const receiptName = 'lasm-package.json';
const lasmVersion = (() => { try { return JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version; } catch { return 'unknown'; } })();
const toml = value => JSON.stringify(value.split('\\').join('/'));

/** The package's lakefile.toml: one library, `Lasm`, whose roots are the modules Lake builds. */
export function lakePackageLakefile({ root = libraryRoot, lazy, version = lasmVersion }) {
  // The version line changes the Lake configuration Lasm's build caches are keyed by when Lasm is upgraded in place.
  return `# Generated by Lasm ${version} (src/lake-library.mjs): Lasm's library modules compiled on first import, for Lake.\n`
    + `name = "${lakePackageName}"\nsrcDir = ${toml(root)}\n\n[[lean_lib]]\nname = "Lasm"\n`
    + `roots = [${lazy.map(module => JSON.stringify(module)).join(', ')}]\n`
    + `moreLeanArgs = ["-Dcompiler.postponeCompile=false"]\n`;
}

/** The package's directory for one Lean prefix and Lasm library, in Lasm's cache. */
export function lakePackageDirectory(prefix, { cache = managedCacheDirectory(), root = libraryRoot } = {}) {
  const key = createHash('sha256').update(JSON.stringify([resolve(prefix), resolve(root)])).digest('hex').slice(0, 16);
  return join(cache, 'lake-library', key);
}

const oleanOf = (base, module) => join(base, ...module.split('.')) + '.olean';

/** Links (or copies) `from` to `to`, replacing what is there. */
function placeFile(from, to) {
  mkdirSync(dirname(to), { recursive: true });
  rmSync(to, { force: true });
  try { linkSync(from, to); } catch { copyFileSync(from, to); }
}

/** Whether `to` is what placeFile(from, to) made: the same file, or a copy with the same bytes. */
function placed(from, to) {
  let a, b;
  try { a = statSync(from); b = statSync(to); } catch { return false; }
  if (a.size !== b.size) return false;
  if (a.ino && a.ino === b.ino && a.dev === b.dev) return true;
  return readFileSync(from).equals(readFileSync(to));
}

/**
 * Creates the package for `prefix` (or checks it): its lakefile, an empty manifest, and the prefix's library
 * .olean files of `eager` in its build directory. Idempotent; replaces anything stale. Returns its directory.
 */
export function ensureLakePackage(prefix, { eager, cache, root = libraryRoot } = {}) {
  const directory = lakePackageDirectory(prefix, { cache, root });
  const lazy = lazyModules(eager, root);
  const lakefile = lakePackageLakefile({ root: resolve(root), lazy });
  const lib = join(directory, '.lake', 'build', 'lib', 'lean');
  const identity = createHash('sha256').update(JSON.stringify({ schema: 1, prefix: resolve(prefix), root: resolve(root), eager, lakefile })).digest('hex');
  let receipt;
  try { receipt = JSON.parse(readFileSync(join(directory, receiptName), 'utf8')); } catch { receipt = undefined; }
  const linked = eager.filter(module => existsSync(oleanOf(join(prefix, 'lib', 'lean'), module)));
  const current = receipt?.identity === identity && readFileOr(join(directory, 'lakefile.toml')) === lakefile
    && linked.every(module => placed(oleanOf(join(prefix, 'lib', 'lean'), module), oleanOf(lib, module)));
  if (current) return directory;
  mkdirSync(directory, { recursive: true });
  // What an earlier receipt linked and this one does not (an older Lasm's library) goes.
  for (const module of receipt?.linked ?? []) if (!linked.includes(module)) rmSync(oleanOf(lib, module), { force: true });
  rmSync(join(directory, receiptName), { force: true });
  writeAtomic(join(directory, 'lakefile.toml'), lakefile);
  writeAtomic(join(directory, 'lake-manifest.json'), JSON.stringify({ version: '1.3.0', packagesDir: '.lake/packages', packages: [], name: lakePackageName, lakeDir: '.lake', fixedToolchain: false }, null, 1) + '\n');
  for (const module of linked) placeFile(oleanOf(join(prefix, 'lib', 'lean'), module), oleanOf(lib, module));
  writeAtomic(join(directory, receiptName), JSON.stringify({ schema: 1, identity, linked }) + '\n');
  return directory;
}

function readFileOr(file) { try { return readFileSync(file, 'utf8'); } catch { return undefined; } }
function writeAtomic(file, text) {
  const temporary = `${file}.tmp-${process.pid}`;
  writeFileSync(temporary, text);
  renameSync(temporary, file);
}

/** Points the project's `.lake/lasm-library` at `directory` (a junction on Windows), replacing a stale link or copy. */
export function ensureProjectLink(project, directory, platform = process.platform) {
  const link = lakeLinkPath(project);
  let stat;
  try { stat = lstatSync(link); } catch { stat = undefined; }
  if (stat) {
    if (stat.isSymbolicLink() || (platform === 'win32' && isJunction(link))) {
      if (sameDirectory(link, directory)) return { link, changed: false };
      unlinkSync(link); // the link only, never what it points to
    } else rmSync(link, { recursive: true, force: true });
  }
  mkdirSync(dirname(link), { recursive: true });
  symlinkSync(directory, link, platform === 'win32' ? 'junction' : 'dir');
  return { link, changed: true };
}

function isJunction(path) { try { readlinkSync(path); return true; } catch { return false; } }
function sameDirectory(link, directory) {
  try { return realpathSync(link) === realpathSync(directory); } catch { return false; }
}

/** The project's Lake configuration file, if any. */
export function lakefileOf(project) {
  for (const name of ['lakefile.toml', 'lakefile.lean']) if (existsSync(join(project, name))) return join(project, name);
  return undefined;
}

/** Whether the project's lakefile requires Lasm's package. */
export function requiresLakePackage(project) {
  const file = lakefileOf(project);
  if (!file) return false;
  const text = readFileSync(file, 'utf8');
  return file.endsWith('.toml')
    ? /^\s*\[\[require\]\][^[]*?^\s*name\s*=\s*"lasm"/m.test(text)
    : /^\s*require\s+(?:"lasm"|«lasm»|lasm)\s+from\b/m.test(text);
}

/** Adds the require to the project's lakefile (lasm editor). Returns whether it changed the file. */
export function addLakeRequire(project) {
  const file = lakefileOf(project);
  if (!file || requiresLakePackage(project)) return false;
  const text = readFileSync(file, 'utf8');
  const separator = text.endsWith('\n\n') || !text.length ? '' : text.endsWith('\n') ? '\n' : '\n\n';
  writeFileSync(file, text + separator + (file.endsWith('.toml') ? lakeRequireToml : lakeRequireLean));
  return true;
}

/**
 * Every lasm command's step for a Lake project: the package for `prefix`, and the project's link to it.
 * Returns { required, directory } (required: the lakefile requires the package, so Lake builds those modules).
 */
export function ensureLakeLibrary(project, prefix, { eager, cache, root } = {}) {
  const directory = ensureLakePackage(prefix, { eager, cache, root });
  ensureProjectLink(project, directory);
  return { required: requiresLakePackage(project), directory };
}
