/** Emscripten labels each --pre-js in the glue with the path it was given.
 * Name these files only by basename, so program.cjs does not depend on the
 * package location or the random build directory. Comments only; no code.
 * Each label must occur exactly once (separators compared portably). */
export function relabelPreJs(glue, files) {
  const portable = path => path.replaceAll('\\', '/');
  const wanted = new Map(files.map(file => [portable(file), portable(file).split('/').pop()]));
  const seen = new Map();
  const result = glue.replace(/^(\/\/ (?:end )?include: )(.*)$/gm, (line, marker, path) => {
    const name = wanted.get(portable(path));
    if (name === undefined) return line;
    seen.set(marker + path, (seen.get(marker + path) ?? 0) + 1);
    return marker + name;
  });
  if (seen.size !== 2 * files.length || [...seen.values()].some(count => count !== 1))
    throw new Error('Unexpected Emscripten pre-js labels in the application glue');
  return result;
}

/** C for trivial initializers (they only call others), as Lean's EmitC writes them. */
export function initializerStubs(stubs) {
  const lines = ['// Generated by Lasm: initializer stubs for planning probes.', '#include <lean/lean.h>', '#include <stdbool.h>'];
  const declared = new Set();
  for (const { calls } of stubs) for (const call of calls) if (!declared.has(call)) { declared.add(call); lines.push(`lean_object* ${call}(uint8_t);`); }
  for (const { name, calls } of stubs) {
    lines.push(`static bool _G_${name}_done = false;`, `LEAN_EXPORT lean_object* ${name}(uint8_t builtin) {`,
      `  if (_G_${name}_done) return lean_io_result_mk_ok(lean_box(0));`, `  _G_${name}_done = true;`, '  lean_object* res;',
      ...calls.map(call => `  res = ${call}(builtin); if (lean_io_result_is_error(res)) return res; lean_dec_ref(res);`),
      '  return lean_io_result_mk_ok(lean_box(0));', '}');
  }
  return lines.join('\n') + '\n';
}

/** The recorded link starts 4 Lean threads' Workers before main runs
 * (-sPTHREAD_POOL_SIZE=4). LASM_THREAD_POOL (0–64) chooses that number when the
 * program starts; further threads start on demand either way. Function
 * platforms run on a fraction of a CPU, where each pre-started Worker's start-up
 * delays the cold start (docs/BENCHMARKS.md "Cold start"). */
export function configurableThreadPool(glue) {
  const recorded = 'var pthreadPoolSize = 4;';
  if (glue.split(recorded).length !== 2) throw new Error('Unexpected Emscripten thread pool in the application glue');
  return glue.replace(recorded, 'var pthreadPoolSize = (value => /^(?:[0-9]|[1-5][0-9]|6[0-4])$/.test(value ?? \'\') ? Number(value) : 4)'
    + '(globalThis.process?.env?.LASM_THREAD_POOL);');
}

/** Link drivers (docs/TOOLCHAIN_SLIMMING.md Phase 2), internal maintainer switch
 * LASM_LINK_DRIVER:
 *   'node'          the default: compiles with clang and performs both links with
 *                   the Node link driver (src/link-driver/link.mjs) using the
 *                   managed link toolchain (src/managed-link-toolchain.mjs): no
 *                   emcc and no Python;
 *   'emcc'          maintainer comparison and recording: emcc from the full
 *                   managed SDK and its private Python;
 *   'node-compile'  milestone B: Node/clang compiles, emcc still links (full SDK). */
export const linkDrivers = Object.freeze(['emcc', 'node-compile', 'node']);
/** Build profiles: 'release' (the recorded final link, byte-reproducible, for
 * deployment) and 'dev' (the same link without Binaryen size optimization, for
 * the edit-run loop; deterministic, larger, never packaged by default). */
export const buildProfiles = Object.freeze(['release', 'dev']);
export const defaultLinkDriver = 'node';
export function selectedLinkDriver(value = process.env.LASM_LINK_DRIVER) {
  if (value === undefined || value === '') return defaultLinkDriver;
  if (linkDrivers.includes(value)) return value;
  throw new Error(`Unsupported LASM_LINK_DRIVER ${JSON.stringify(value)}`);
}

/** Object-store entries (generated objects, probe records): a magic, the
 * SHA-256 of the content, then the content; written atomically. */
const storeMagic = Buffer.from('LASMSTO1');
let storePartials = 0;
export function writeStoreEntry(path, bytes) {
  // Two build workers of one process (lasm dev) may write the same entry: the thread is part of the name.
  const partial = `${path}.${process.pid}.${threadId}.${storePartials++}.partial`;
  writeFileSync(partial, Buffer.concat([storeMagic, createHash('sha256').update(bytes).digest(), bytes]));
  renameSync(partial, path);
}
/** The content of a valid entry; a missing, damaged or foreign one is removed and reads as undefined. */
export function readStoreEntry(path) {
  let data;
  try { data = readFileSync(path); } catch { return undefined; }
  const bytes = data.subarray(storeMagic.length + 32);
  if (data.length >= storeMagic.length + 32 && data.subarray(0, storeMagic.length).equals(storeMagic)
      && createHash('sha256').update(bytes).digest().equals(data.subarray(storeMagic.length, storeMagic.length + 32))) return bytes;
  rmSync(path, { force: true });
  return undefined;
}

/** The machine-wide store of Lasm's planning objects and probe records keeps the
 * most recently used entries within a bound; this build's entries are kept. */
export const sharedStoreLimits = Object.freeze({ entries: 600, bytes: 768 * 1024 * 1024 });
export function pruneSharedStore(directory, used, limits = sharedStoreLimits) {
  const now = new Date();
  for (const path of used) { try { utimesSync(path, now, now); } catch { /* removed meanwhile */ } }
  let entries;
  try { entries = readdirSync(directory).filter(name => !name.endsWith('.partial')).map(name => {
    try { const stat = statSync(join(directory, name)); return { path: join(directory, name), size: stat.size, time: stat.mtimeMs }; }
    catch { return undefined; } }).filter(Boolean); } catch { return; }
  let bytes = entries.reduce((total, entry) => total + entry.size, 0), count = entries.length;
  for (const entry of entries.sort((a, b) => a.time - b.time)) {
    if (count <= limits.entries && bytes <= limits.bytes) break;
    if (used.has(entry.path)) continue;
    rmSync(entry.path, { force: true }); count--; bytes -= entry.size;
  }
}

/** The code that turns a probe's arguments into wasm-ld's inputs. */
let driverSources;
function linkDriverSourceIdentity() {
  if (driverSources) return driverSources;
  const hash = createHash('sha256');
  const directory = new URL('./link-driver/', import.meta.url);
  for (const name of readdirSync(directory).sort()) hash.update(name + '\0').update(readFileSync(new URL(name, directory)));
  for (const name of ['application-link.mjs', 'platform.mjs']) hash.update(name + '\0').update(readFileSync(new URL(`./${name}`, import.meta.url)));
  return driverSources = hash.digest('hex');
}

/** Initializer units of the runtime's (verified, immutable) archives, kept per
 * machine: keyed by the runtime identity, the archive and the analysis code. */
const analysisSources = ['application-initialization.mjs', 'wasm-objects.mjs'];
/** The analysis shipped beside the runtime bundle (scripts/package-node-release.mjs). */
export const shippedAnalysisDirectory = runtime => join(runtime.directory + '.analysis');
export function archiveUnitCache(directory, runtime, { shipped = shippedAnalysisDirectory(runtime) } = {}) {
  const analyzer = createHash('sha256');
  for (const name of analysisSources) analyzer.update(readFileSync(new URL(`./${name}`, import.meta.url)));
  const key = file => createHash('sha256').update(JSON.stringify({ schema: 1, runtime: runtime.identity,
    archive: relative(runtime.directory, file).replaceAll('\\', '/'), analyzer: analyzer.copy().digest('hex') })).digest('hex');
  const name = file => `initializer-units-${key(file)}.json`;
  const path = file => join(directory, name(file));
  return {
    load(file) {
      if (relative(runtime.directory, file).startsWith('..')) return undefined;
      for (const candidate of [path(file), ...(shipped ? [join(shipped, name(file))] : [])]) {
        try {
          const record = JSON.parse(readFileSync(candidate, 'utf8'));
          if (record.schema === 1 && record.key === key(file) && Array.isArray(record.units)) return record.units;
        } catch { /* try the next */ }
      }
      return undefined;
    },
    save(file, units) {
      if (relative(runtime.directory, file).startsWith('..')) return;
      try {
        mkdirSync(directory, { recursive: true });
        const partial = `${path(file)}.${process.pid}.${threadId}.partial`;
        writeFileSync(partial, JSON.stringify({ schema: 1, key: key(file), units }));
        renameSync(partial, path(file));
      } catch { /* An unwritable cache only costs the next build the analysis. */ }
    },
  };
}

/** Diagnostics for a rejected probe link; never masks the rejection itself. */
function rejectionExplanation({ requirements, whyExtractFile, objects, runtime, nm }) {
  try {
    const nmText = args => execFileSync(nm, args, { encoding: 'utf8', maxBuffer: 1024 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
    const members = runtime.manifest.libraries.filter(name => !/lib(?:lasmsymbols|gmp)\.a$/.test(name))
      .flatMap(name => archiveMembers(join(runtime.directory, name), nmText([join(runtime.directory, name)])));
    return explainRejection({ rows: parseWhyExtract(readFileSync(whyExtractFile, 'utf8')), userObjects: objects, requirements,
      members, userSymbols: undefinedSymbols(nmText(['--undefined-only', ...objects])) });
  } catch { return []; }
}

export async function linkApplication(options) {
  const { runtime, profile = 'release', linkDriver = selectedLinkDriver(), initializationSeed } = options;
  // initializationSeed: a file recording the initializer units the project's
  // previous build kept. A dev build starts its plan from them and lets the
  // delivered link itself be the planning round (one wasm-ld instead of three);
  // release builds only write it. A seeded build that the application policy
  // rejects is retried unseeded, so the seed never changes what is accepted.
  const seedRecord = readInitializationSeed(initializationSeed, runtime);
  const seeded = profile === 'dev' && linkDriver === 'node' && !!seedRecord && !process.env.LASM_LINK_DEBUG;
  if (seeded) {
    try { return await linkApplicationOnce(options, seedRecord); }
    catch (error) {
      if (error.code !== 'ERR_LASM_UNSUPPORTED_RUNTIME_FEATURE') throw error;
    }
  }
  return linkApplicationOnce(options);
}

/** The seed record of a previous build of this project (see linkApplication). */
function readInitializationSeed(file, runtime) {
  if (!file) return undefined;
  try {
    const record = JSON.parse(readFileSync(file, 'utf8'));
    if (record.schema === 1 && record.runtime === runtime.identity && Array.isArray(record.keep)) return record;
  } catch { /* none yet */ }
  return undefined;
}

async function linkApplicationOnce({ sources, sdk, runtime, work, dist, leanVersion, memoryMode, verbose = true, progress,
  linkDriver = selectedLinkDriver(), linkIntermediates, objectCache, sharedCache, analysisCache, profile = 'release', initialization = process.env.LASM_INITIALIZATION, nativeCompilations = [], nativeUnavailable: declaredUnavailable = [],
  initializationSeed, timings, linkOnly = false }, seedRecord) {
  const seed = seedRecord && new Set(seedRecord.keep);
  const nativeUnavailable = [...declaredUnavailable];
  const time = (name, start) => { if (timings) timings[name] = (timings[name] ?? 0) + performance.now() - start; };
  let initializationPlan;
  if (![1, 2].includes(memoryMode)) throw new Error('Invalid application memory mode');
  // The recipe records memory mode 1 only (MEMORY64=1, 8 GiB maximum).
  if (linkDriver === 'node' && memoryMode !== 1) throw new Error('The Node link driver has no recording for this memory mode');
  if (!Array.isArray(sources) || !sources.length) throw new Error('Application C sources are required');
  if (leanVersion !== runtime.manifest.lean) throw new Error('Application and runtime versions differ');
  const compileFlags = ['-O2', '-DNDEBUG', '-pthread', '-fwasm-exceptions', '-fPIC', '-DLEAN_EMSCRIPTEN',
    '-sMEMORY64=1', '-ffunction-sections', '-fdata-sections', '-I', join(runtime.directory, 'include')];
  // Ordinary CLI users need Lean diagnostics and build progress. Detailed
  // generated-C/SDK warnings remain available with --verbose; failures retain
  // their captured diagnostics for the CLI's error reporter.
  if (!linkDrivers.includes(linkDriver)) throw new Error('Invalid application link driver');
  if (!buildProfiles.includes(profile)) throw new Error(`Invalid build profile ${JSON.stringify(profile)}`);
  if (profile === 'dev' && linkDriver !== 'node') throw new Error('The dev build profile needs the Node link driver');
  const nodeLink = linkDriver === 'node', nodeCompile = linkDriver !== 'emcc';
  // The Node driver never runs emcc, em++ or Python: any SDK driver call is a bug.
  const execute = nodeLink ? tool => { throw new Error(`The Node link driver must not run ${tool}`); }
    : (tool, args) => sdk.execute(tool, args, {
      stdio: verbose ? 'inherit' : ['ignore', 'pipe', 'pipe'], timeout: 1800_000, maxBuffer: 8 * 1024 * 1024,
    });
  if (nodeCompile && !existsSync(join(emscriptenCache(sdk), 'sysroot_install.stamp')))
    throw new Error('The Node compile driver needs installed Emscripten system headers (a prebuilt or emcc-initialized cache)');
  const recipe = nodeCompile ? bundledRecipe() : undefined;
  if (nodeCompile) checkToolchainIdentity(recipe, sdk);
  // Tool diagnostics as emcc shows them: inherited with --verbose, else captured for the error reporter.
  const toolStdio = verbose ? ['ignore', 'inherit', 'inherit'] : ['ignore', 'pipe', 'pipe'];
  let jsSteps;
  const runLinkOnce = (mode, args, { mapOnly = false, optimize = true } = {}) => {
    if (!nodeLink) return execute('em++', args);
    const temp = linkTemporaryDirectory(work, mode);
    try {
      return linkWithNode({ recipe, mode, args: args.flatMap(arg => arg.startsWith('@') ? readResponseArguments(arg.slice(1)) : [arg]),
        sdk, cache: emscriptenCache(sdk), temp, intermediates: linkIntermediates && join(linkIntermediates, mode),
        nativeSigs: bundledNativeSigs(recipe), stdio: toolStdio, mapOnly, optimize, stepCache: jsSteps });
    } finally { removeTemporary(temp); }
  };
  // A link that fails on undefined symbols names the native libraries the program
  // declared but Lasm could not compile, and known prebuilt libraries by symbol.
  const linkFailure = error => {
    const output = `${error.stderr ?? ''}\n${error.stdout ?? ''}\n${error.message ?? ''}`;
    const symbols = linkUndefinedSymbols(output);
    const known = librariesForUndefinedSymbols(output).filter(({ library }) => !nativeUnavailable.some(item => describeLibrary(item.library).name === library));
    if (symbols.length && (nativeUnavailable.length || known.length))
      return Object.assign(new UnsupportedNativeLibrary([...nativeUnavailable, ...known.map(({ library }) => ({ library }))], symbols), { cause: error });
    return error;
  };
  const runLink = (...args) => {
    try { return runLinkOnce(...args); }
    catch (error) { throw linkFailure(error); }
  };
  // A map-only probe link whose wasm-ld runs asynchronously, so independent
  // planning probes overlap (the Node driver; the emcc driver links in turn).
  const runProbeLink = async args => {
    if (!nodeLink) return runLink('probe', args, { mapOnly: true });
    const temp = linkTemporaryDirectory(work, 'probe');
    try {
      const command = linkWithNode({ recipe, mode: 'probe', args: args.flatMap(arg => arg.startsWith('@') ? readResponseArguments(arg.slice(1)) : [arg]),
        sdk, cache: emscriptenCache(sdk), temp, nativeSigs: bundledNativeSigs(recipe), stdio: toolStdio, mapOnly: 'command', stepCache: jsSteps });
      await new Promise((resolve, reject) => execFile(command.program, command.args, { env: command.env, windowsHide: true,
        timeout: 1800_000, maxBuffer: 512 * 1024 * 1024 }, (error, stdout, stderr) => {
        if (verbose) { process.stdout.write(stdout); process.stderr.write(stderr); }
        error ? reject(Object.assign(error, { stdout, stderr })) : resolve();
      }));
    } catch (error) { throw linkFailure(error); }
    finally { removeTemporary(temp); }
  };
  const compileUncached = (source, object, optimization) => nodeCompile
    ? compileObject({ sdk, flags: compileFlags, source, object, optimization, settings: {
      stdio: verbose ? 'inherit' : ['ignore', 'pipe', 'pipe'], timeout: 1800_000, maxBuffer: 8 * 1024 * 1024 } })
    : execute('emcc', [...compileFlags, '-c', source, '-o', object]);
  const objects = [];
  // Generated C (Lean modules, and Lasm's own initializer wrappers and stubs)
  // reuses its object from this or the project's previous build: the key covers
  // the C bytes, the compiler flags (without the runtime path), the runtime
  // identity, the compiler tools and the link driver. Same key, same object bytes.
  const objectKey = (source, optimization) => createHash('sha256').update(JSON.stringify({ schema: 1, runtime: runtime.identity, linkDriver,
    tools: sdk.toolchain ?? sdk.driverIdentity ?? null, flags: compileFlags.filter(flag => flag !== join(runtime.directory, 'include')),
    ...(optimization ? { optimization } : {}) }))
    .update(readFileSync(source)).digest('hex');
  const usedObjects = new Set();
  // Without a project cache, identical C within this build still compiles once
  // (the last planning round's wrappers are the final link's).
  const objectStore = objectCache ?? join(work, 'object-store');
  mkdirSync(objectStore, { recursive: true });
  // Lasm's own generated C (initializer wrappers, stubs) and the planning probe
  // records do not depend on the project: with `sharedCache` (the managed cache)
  // a new project reuses them. Bounded below; entries are content-addressed.
  const sharedStore = sharedCache ?? objectStore, sharedUsed = new Set();
  mkdirSync(sharedStore, { recursive: true });
  const use = (store, name) => { const path = join(store, name); (store === objectStore ? usedObjects : sharedUsed).add(path); return path; };
  // Emscripten's JavaScript link steps, reused by content (src/link-driver/link.mjs jsStepCache).
  jsSteps = { get: key => readStoreEntry(use(sharedStore, `js-${key}.txt`))?.toString('utf8'),
    set: (key, text) => { try { writeStoreEntry(use(sharedStore, `js-${key}.txt`), Buffer.from(text)); } catch { /* not cached */ } } };
  // Entries carry their own SHA-256 (readStoreEntry): a damaged, truncated or
  // concurrently pruned entry is compiled again and replaced.
  const reuse = (cached, object) => {
    const bytes = readStoreEntry(cached);
    if (!bytes) return false;
    writeFileSync(object, bytes); return true;
  };
  const storeObject = (object, cached) => writeStoreEntry(cached, readFileSync(object));
  const compile = (source, object, { shared = false, optimization } = {}) => {
    const cached = use(shared ? sharedStore : objectStore, objectKey(source, optimization) + '.o');
    if (existsSync(cached) && reuse(cached, object)) return;
    compileUncached(source, object, optimization);
    storeObject(object, cached);
  };
  // Identity of a planning probe link: the bytes of every input Lasm generated,
  // the runtime archives by the runtime identity, Lasm's own JS by content, and
  // every flag; the map and output paths do not affect the live set.
  const toolIdentity = JSON.stringify({ schema: 1, runtime: runtime.identity, linkDriver, tools: sdk.toolchain ?? sdk.driverIdentity ?? null,
    recipe: recipe ? createHash('sha256').update(JSON.stringify(recipe)).digest('hex') : null, driver: linkDriverSourceIdentity() });
  const probeKey = args => {
    const hash = createHash('sha256').update(toolIdentity);
    for (let index = 0; index < args.length; index++) {
      const arg = args[index];
      if (arg.startsWith('-Wl,-Map=')) continue;
      if (arg === '-o') { index++; continue; }
      const exportsList = /^-sEXPORTED_FUNCTIONS=@(.+)$/.exec(arg);
      const inside = (directory, file) => !relative(directory, file).startsWith('..') && !isAbsolute(relative(directory, file));
      if (exportsList) hash.update('exports\0').update(readFileSync(exportsList[1]));
      else if (isAbsolute(arg) && inside(runtime.directory, arg)) hash.update('runtime\0' + relative(runtime.directory, arg).replaceAll('\\', '/'));
      else if (isAbsolute(arg) && existsSync(arg) && statSync(arg).isFile()) hash.update('file\0').update(readFileSync(arg));
      else hash.update('arg\0' + arg);
      hash.update('\0');
    }
    return hash.digest('hex');
  };
  // Several sources at once (the initializer wrapper parts): cached objects are
  // copied, the others compile concurrently, up to the build's job count.
  const compileAll = async (pairs, { optimization } = {}) => {
    const pending = [];
    for (const [source, object] of pairs) {
      const cached = use(sharedStore, objectKey(source, optimization) + '.o');
      if (!(existsSync(cached) && reuse(cached, object))) pending.push({ source, object, cached });
    }
    // The emcc maintainer driver has no probe optimization level: it compiles as recorded.
    if (!nodeCompile || pending.length < 2 && !optimization) { for (const item of pending) { compileUncached(item.source, item.object); storeObject(item.object, item.cached); } return; }
    const run = item => compileObject({ sdk, flags: compileFlags, source: item.source, object: item.object, optimization,
      execute: (program, args, options) => new Promise((resolve, reject) => execFile(program, args, options, (error, stdout, stderr) =>
        error ? reject(Object.assign(error, { stdout, stderr })) : resolve(stdout))),
      settings: { timeout: 1800_000, maxBuffer: 8 * 1024 * 1024 } }).then(() => { storeObject(item.object, item.cached); });
    const queue = [...pending], jobs = Math.max(1, Math.min(buildJobs(sdk.env), queue.length));
    await Promise.all(Array.from({ length: jobs }, async () => { while (queue.length) await run(queue.shift()); }));
  };
  for (let index = 0; index < sources.length; index++) {
    progress?.({ stage: `Compiling application module ${index + 1} of ${sources.length}` });
    const object = join(work, `module-${index}.o`);
    compile(sources[index], object, { optimization: profile === 'dev' && nodeCompile ? devOptimization : undefined });
    objects.push(object);
  }
  // Package C code (src/application-native.mjs), linked like archive members:
  // only objects that the program reaches are kept.
  const nativeObjects = [];
  for (let index = 0; index < nativeCompilations.length; index++) {
    const item = nativeCompilations[index];
    progress?.({ stage: `Compiling package C code ${index + 1} of ${nativeCompilations.length}` });
    const object = join(work, `native-${index}.o`);
    const key = createHash('sha256').update(JSON.stringify({ schema: 1, native: item.identity, args: item.extraArgs, runtime: runtime.identity,
      linkDriver, tools: sdk.toolchain ?? sdk.driverIdentity ?? null })).update(readFileSync(item.source)).digest('hex');
    const cached = objectCache && join(objectCache, key + '.o');
    if (cached && existsSync(cached) && reuse(cached, object)) { /* reused */ }
    else {
      if (!nodeCompile) throw new Error('Package C code requires the Node compile driver');
      try {
        compileObject({ sdk, flags: compileFlags, source: item.source, object, extraArgs: item.extraArgs, settings: {
          stdio: verbose ? 'inherit' : ['ignore', 'pipe', 'pipe'], timeout: 1800_000, maxBuffer: 8 * 1024 * 1024, cwd: item.cwd } });
      } catch (error) {
        // Code a package needs only natively (a tactic's C++ backend) need not compile
        // for Wasm; the link reports it if the program actually reaches its symbols.
        const reason = String(error.stderr ?? error.message).split(/\r?\n/).find(line => /error/.test(line))?.trim();
        nativeUnavailable.push({ package: item.package, library: item.source,
          reason: `does not compile for WebAssembly${reason ? ': ' + reason.slice(0, 200) : ''}` });
        continue;
      }
      if (cached) storeObject(object, cached);
    }
    if (cached) usedObjects.add(cached);
    nativeObjects.push(object);
  }
  if (nativeObjects.length) {
    const stubC = join(work, 'package-dl.c'), stubObject = join(work, 'package-dl.o');
    await writeFile(stubC, dynamicLoadingStubs); compile(stubC, stubObject, { shared: true }); nativeObjects.push(stubObject);
  }
  const nativeInputs = nativeObjects.length ? ['-Wl,--start-lib', ...nativeObjects, '-Wl,--end-lib'] : [];
  progress?.({ stage: 'Preparing application symbols' });
  // llvm-nm listings of this build's objects, reused by object content.
  const nmProgram = join(sdk.prefix, 'bin', executableName('llvm-nm'));
  const nmText = (args, file) => {
    const cached = use(objectStore, `nm-${createHash('sha256').update(JSON.stringify(args)).update(readFileSync(file)).digest('hex')}.txt`);
    const saved = readStoreEntry(cached);
    if (saved) return saved.toString('utf8');
    const text = execFileSync(nmProgram, [...args, file], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, windowsHide: true });
    writeStoreEntry(cached, Buffer.from(text));
    return text;
  };
  const registry = readApplicationSymbols(sources, objects, nmProgram, runtime.manifest.applicationSymbolHook, { nmText });
  const probeC = join(work, 'reachability.c'), probeObject = join(work, 'reachability.o');
  await writeFile(probeC, reachabilityRegistry);
  compile(probeC, probeObject, { shared: true });
  const initializeObject = join(work, 'initialization.o');
  const specializeInitialization = canSpecializeInitialization(runtime);
  const analysis = { initializationFreeCppSymbols: specializeInitialization
    ? readInitializationFreeCppSymbols(join(runtime.directory, 'lib/libleancpp.a'),
      join(sdk.prefix, 'bin', executableName('llvm-nm'))) : new Set() };
  const initializationInputs = [];
  if (specializeInitialization) {
    const initializeC = join(work, 'initialization.c'); await writeFile(initializeC, selectiveInitialization);
    compile(initializeC, initializeObject, { shared: true });
    initializationInputs.push(initializeObject, '-Wl,--wrap=lean_initialize');
  }
  // A C entry point `int main(void)` defines only __main_void. The exported `main`
  // (__main_argc_argv) would then resolve to the first archive member defining it:
  // since Lean 4.35, upstream LeanExport's tool `main`, which pulls Lean's compiler
  // (upstream misc_dir/rc_sticky was rejected). Define it as Emscripten's libc does.
  const definedEntries = new Set(objects.flatMap(file => nmText(['--defined-only', '--extern-only', '--just-symbol-name'], file).split(/\r?\n/)));
  const entryObject = join(work, 'entry.o');
  if (definedEntries.has('__main_void') && !definedEntries.has('__main_argc_argv')) {
    const entryC = join(work, 'entry.c');
    await writeFile(entryC, 'int __main_void(void);\nint __main_argc_argv(int argc, char **argv) { return __main_void(); }\n');
    compile(entryC, entryObject, { shared: true });
    initializationInputs.push(entryObject);
  }
  const exportsFile = join(work, 'exports.json');
  // Explicit application C exports remain roots. Ordinary Lean declarations,
  // data and imported standard libraries follow the linker's reachability.
  const staticExports = [...new Set(['_main', '_malloc', '_free', ...registry.foreignExports])].sort();
  await writeFile(exportsFile, JSON.stringify(staticExports) + '\n');
  // Bake the verified release into the private runtime prelude. It must not
  // depend on mutable process environment or alter Lean's visible environment.
  const applicationPrelude = join(work, 'application-pre.js');
  await writeFile(applicationPrelude, `Module.lasmLeanVersion = ${JSON.stringify(leanVersion)};\n`);
  const preJs = [join(root, 'scripts/full-lean/emscripten-pre.js'), applicationPrelude, join(root, 'scripts/full-lean/host-pre.js')];
  const mapFile = join(work, 'reachability.map'), whyExtractFile = join(work, 'why-extract.txt');
  // The checked loader transformations use LF templates. Emscripten otherwise
  // defaults to host line endings, making identical Windows output look like
  // semantic drift. Ask the pinned driver to emit the same format everywhere.
  // Planning probes write their own (discarded) program: one may still be
  // running when a seeded dev build's delivered link has written dist/.
  const linkWith = (exports, output = join(dist, 'program.cjs')) => ['--output-eol=linux', '-pthread', '-fwasm-exceptions', `-sMEMORY64=${memoryMode}`, '-sMALLOC=mimalloc',
    '-sMAIN_MODULE=2', `-sEXPORTED_FUNCTIONS=@${exports}`, '-sPROXY_TO_PTHREAD=1', '-sPTHREAD_POOL_SIZE=4',
    '-sEXPORTED_RUNTIME_METHODS=stringToNewUTF8', '-sEXIT_RUNTIME=1', '-sNODERAWFS=1',
    '-sALLOW_MEMORY_GROWTH=1', '-sGROWABLE_ARRAYBUFFERS=1', '-sSTACK_OVERFLOW_CHECK=2',
    '-Wl,--export-if-defined=__cpp_exception', '-sINITIAL_MEMORY=134217728',
    `-sMAXIMUM_MEMORY=${memoryMode === 1 ? 8589934592 : 4294967296}`, '-sSTACK_SIZE=67108864',
    '-Wno-experimental', '-Wno-pthreads-mem-growth', '-Wl,--start-group',
    ...runtime.manifest.libraries.map(name => join(runtime.directory, name)), '-Wl,--end-group',
    ...preJs.flatMap(file => ['--pre-js', file]),
    '--js-library', join(root, 'scripts/full-lean/host-library.js'), '-o', output];
  const link = linkWith(exportsFile);
  const argumentsFile = join(work, 'link.rsp');
  // Runtime initialization plan (src/application-initialization.mjs): initializers
  // of build-time-only modules (tactics, elaborators, attributes) are not linked.
  // A map-only probe link. wasm-ld's live set and the runtime requirements read
  // from its map are a function of the link inputs (probeKey): an unchanged probe
  // (a later planning round, the program-independent probes of a one-line edit,
  // or the requirements check repeating the last round) is not relinked.
  const probeLink = async (args, map, rsp, { kind, output } = {}) => {
    const cached = use(sharedStore, `probe-${probeKey(args)}.json`);
    try {
      const record = JSON.parse(readStoreEntry(cached)?.toString('utf8') ?? 'null');
      if (record?.schema === 2) return { live: { data: new Set(record.data), code: new Set(record.code) },
        requirements: record.requirements, requirementsError: record.requirementsError };
    } catch { /* not recorded */ }
    // Dev builds: the body probes link with the runtime members their previous
    // full run kept (as the final link does), checked by its imports. The live
    // set is then the full link's, so it is recorded under the same key.
    const subset = kind && output && profile === 'dev' && nodeLink && seedRecord?.probes?.[kind];
    let linked = false;
    if (subset && Object.keys(subset.liveMembers).every(archive => runtimeArchives.includes(archive))) {
      try {
        const libraries = memberFiles(subset.liveMembers, memberDirectory);
        await writeFile(rsp, responseFile(args.flatMap(arg => arg === runtimeArchives[0] ? libraries : runtimeArchives.includes(arg) ? [] : [arg])));
        await runProbeLink(['@' + rsp]);
        const imports = wasmImports(output), allowed = new Set(subset.imports);
        linked = !!imports && imports.every(item => allowed.has(item));
        if (linked) (seedOut ??= {}).probes = { ...seedOut.probes, [kind]: subset };
      } catch { /* link in full */ }
    }
    if (!linked) {
      await writeFile(rsp, responseFile(args));
      await runProbeLink(['@' + rsp]);
      if (kind && output && profile === 'dev' && nodeLink && statSync(map).size < 64 * 1024 * 1024) {
        try {
          const imports = wasmImports(output);
          if (imports) (seedOut ??= {}).probes = { ...seedOut.probes, [kind]: { liveMembers: liveMembers(readFileSync(map, 'utf8'), runtimeArchives), imports } };
        } catch { /* no subset next time */ }
      }
    }
    const live = await readLiveSymbols(map);
    // Planning probes of initializer bodies have no application entry point.
    let requirements = null, requirementsError = null;
    // Body probes (kind) have no entry point: their requirements are never read.
    if (kind) requirementsError = 'initializer body probe';
    else try { requirements = await readApplicationLinkRequirements(map, analysis); } catch (error) { requirementsError = error.message; }
    writeStoreEntry(cached, Buffer.from(JSON.stringify({ schema: 2, data: [...live.data].sort(), code: [...live.code].sort(), requirements, requirementsError })));
    return { live, requirements, requirementsError };
  };
  const planInputs = [], planWrap = [], planObjects = [];
  // The delivered link. -g1 preserves checked JS loader shapes without Wasm
  // names or DWARF. Maintainer diagnostics only: LASM_LINK_DEBUG delivers the
  // unoptimized probe link (with Wasm names).
  const finalMap = join(work, 'final.map');
  const debug = !!process.env.LASM_LINK_DEBUG;
  // Dev builds (src/application-live-members.mjs): the runtime members the
  // previous full link kept, instead of the archives; accepted only when the
  // program imports nothing that link did not.
  const runtimeArchives = runtime.manifest.libraries.map(name => join(runtime.directory, name));
  const memberDirectory = join(dirname(sharedStore), 'members', runtime.identity.slice(0, 32));
  let fullLinked = false;
  // A link-only build checks the linked Wasm before Emscripten's finalize step: its own import record.
  const importsKey = linkOnly ? 'importsLinked' : 'imports';
  const fastMembers = profile === 'dev' && nodeLink && seedRecord?.liveMembers && seedRecord?.[importsKey]
    && Object.keys(seedRecord.liveMembers).every(archive => runtimeArchives.includes(archive)) ? seedRecord : undefined;
  const linkOnce = async (plannedInputs, members) => {
    const libraries = members ? memberFiles(members, memberDirectory) : undefined;
    const args = libraries ? link.flatMap(arg => arg === runtimeArchives[0] ? libraries : runtimeArchives.includes(arg) ? [] : [arg]) : link;
    await writeFile(argumentsFile, responseFile([...objects, ...nativeInputs, ...initializationInputs, ...plannedInputs,
      ...(debug ? ['-O0'] : ['-Oz', '-g1']), '-Wl,-Map=' + finalMap, ...args]));
    progress?.({ stage: 'Linking application and Lean runtime' });
    const start = performance.now();
    try { runLink(debug ? 'probe' : 'final', ['@' + argumentsFile], { optimize: debug || profile === 'release', mapOnly: linkOnly }); }
    finally { time('final link', start); }
  };
  const finalLink = async plannedInputs => {
    if (fastMembers) {
      try {
        await linkOnce(plannedInputs, fastMembers.liveMembers);
        const imports = wasmImports(join(dist, 'program.wasm')), allowed = new Set(fastMembers[importsKey]);
        if (imports && imports.every(item => allowed.has(item))) { fullLinked = false; return; }
      } catch { /* link in full below */ }
    }
    await linkOnce(plannedInputs);
    fullLinked = true;
  };
  let seededFinal, seedOut;
  if (!['all', 'native'].includes(initialization)) {
    const wrapperFiles = (kind = '') => Array.from({ length: initializerWrapperParts }, (_, part) =>
      [join(work, `initializers${kind}-${part}.c`), join(work, `initializers${kind}-${part}.o`)]);
    const finalWrappers = wrapperFiles(), probeWrappers = wrapperFiles('-probe');
    // Planning probes only read wasm-ld's live set: their wrapper objects are
    // compiled at -O0 (src/link-driver/compile.mjs probeOptimization). The
    // wrappers of the delivered program are compiled as recorded.
    let probeCount = 0;
    const writeWrappers = async (sources, { probe = false, files = probe ? probeWrappers : finalWrappers } = {}) => {
      for (let part = 0; part < files.length; part++) await writeFile(files[part][0], sources[part]);
      await compileAll(files, nodeCompile && probe ? { optimization: probeOptimization } : {});
      return files.map(([, object]) => object);
    };
    const bodiesExports = join(work, 'initializers-exports.json');
    await writeFile(bodiesExports, JSON.stringify(['_main', '_malloc', '_free']) + '\n');
    progress?.({ stage: 'Planning runtime initialization' });
    const plan = await planInitializers({ objects, archives: runtime.manifest.libraries.map(name => join(runtime.directory, name)),
      archiveUnits: analysisCache && archiveUnitCache(analysisCache, runtime),
      // One build job (LASM_BUILD_JOBS=1, the maintainer guard): probes in turn.
      concurrent: nodeLink && buildJobs(sdk.env) > 1,
      log: verbose ? message => console.error(message) : () => {},
      forceKeep: process.env.LASM_INITIALIZATION_KEEP ? new RegExp(process.env.LASM_INITIALIZATION_KEEP) : undefined,
      initTargets: (core => core && new Set([...core, ...sources.flatMap(file => cInitTargets(readFileSync(file, 'utf8')))]))(coreInitTargets(leanVersion)),
      seed, trimBodies: profile === 'dev',
      async probe(source, wrapFlags, { bodies = false, exclude, kind, stubs = [] } = {}) {
        // A seeded dev build: each planning round is the delivered link itself.
        if (seed && !bodies) {
          const wrappers = await writeWrappers(source);
          await finalLink([probeObject, ...wrappers, ...wrapFlags]);
          seededFinal = { source, wrapFlags };
          const start = performance.now();
          try { return await readLiveSymbols(finalMap); } finally { time('read map', start); }
        }
        // Probes may run concurrently: each has its own files.
        const id = probeCount++, map = join(work, `initializers-${id}.map`);
        const wrappersObjects = await writeWrappers(source, { probe: true, files: wrapperFiles(`-probe-${id}`) });
        const excluded = new Set([exclude].flat());
        // Stubs of left-out trivial initializers (src/application-initialization.mjs trimBodies).
        const stubObjects = [];
        if (stubs.length) {
          const stubC = join(work, `initializer-stubs-${id}.c`), stubO = join(work, `initializer-stubs-${id}.o`);
          await writeFile(stubC, initializerStubs(stubs));
          await compileAll([[stubC, stubO]], nodeCompile ? { optimization: probeOptimization } : {});
          stubObjects.push(stubO);
        }
        const args = [...objects.filter(file => !excluded.has(file)), ...stubObjects, ...nativeInputs, probeObject, ...wrappersObjects,
          ...initializationInputs.filter(file => !bodies || file !== entryObject),
          '-O0', '-Wl,-Map=' + map, ...wrapFlags, ...linkWith(bodies ? bodiesExports : exportsFile, join(work, `initializers-${id}.cjs`))];
        return (await probeLink(args, map, join(work, `initializers-${id}.rsp`), { kind: bodies ? kind : undefined, output: join(work, `initializers-${id}.wasm`) })).live;
      } });
    if (plan?.skipped.length && !plan.shared.length) {
      // The plan itself, for links that regenerate the wrappers from it (the
      // edge and browser link's compact form: src/edge/edge-initializers.mjs).
      const inPlan = new Set(plan.closure);
      await writeFile(join(work, 'initialization-plan.json'), JSON.stringify({ schema: 1, closure: plan.closure, keep: [...plan.keep],
        calls: Object.fromEntries(plan.closure.map(name => [name, plan.units.get(name).calls.filter(call => inPlan.has(call))])) }) + '\n');
      const planned = initializerWrappers(plan.units, plan.closure, { keep: plan.keep, parts: initializerWrapperParts });
      // A seeded plan whose last round linked exactly these wrappers is delivered as linked.
      if (seededFinal && seededFinal.wrapFlags.join('\0') === plan.wrap.join('\0')
          && seededFinal.source.every((text, part) => text === planned[part])) seededFinal.delivered = true;
      planInputs.push(...await writeWrappers(planned), ...plan.wrap); planWrap.push(...plan.wrap);
      // The requirements check repeats the last planning round's link (the same
      // probe objects, from the object store), so its recorded result is reused.
      if (!seededFinal?.delivered) planObjects.push(...await writeWrappers(planned, { probe: true }));
      initializationPlan = { units: plan.closure.length, kept: plan.keep.size, skipped: plan.skipped.length };
    } else if (plan) initializationPlan = { units: plan.closure.length, kept: plan.closure.length, skipped: 0,
      ...(plan.shared.length ? { sharedGlobals: plan.shared.slice(0, 20) } : {}) };
    if (plan) seedOut = { ...seedOut, keep: [...plan.keep].sort() };
  }
  const delivered = !!seededFinal?.delivered;
  // Classify the live graph before expensive optimization. In particular, a
  // runtime evaluator must not optimize the full compiler twice. The inputs are
  // the final link's (the planned wrappers, in the planning probes' order, so the
  // last planning round's identical link is reused).
  const requirementsInputs = [...objects, ...nativeInputs, probeObject, ...planObjects, ...initializationInputs,
    '-O0', '-Wl,-Map=' + mapFile, ...planWrap, ...link];
  progress?.({ stage: 'Checking required runtime code' });
  // A delivered seeded link included the lookup marker, as the probes do: its
  // map answers the same question.
  const checked = delivered ? { requirements: await readApplicationLinkRequirements(finalMap, analysis) }
    : await probeLink(requirementsInputs, mapFile, argumentsFile);
  if (!checked.requirements) throw new Error(checked.requirementsError ?? 'Unreadable application linker map');
  const requirements = structuredClone(checked.requirements);
  // --why-extract (rejection diagnostics only) comes from one more probe link.
  const explainRejection = () => {
    writeFileSync(argumentsFile, responseFile([...objects, ...nativeInputs, probeObject, ...initializationInputs, ...planInputs,
      '-O0', '-Wl,-Map=' + mapFile, '-Wl,--why-extract=' + whyExtractFile, ...link]));
    runLink('probe', ['@' + argumentsFile], { mapOnly: true });
  };
  requirements.specializedInitialization = specializeInitialization && requirements.mode === 'static';
  if (initializationPlan) requirements.initializationPlan = initializationPlan;
  // Fail during the build, before a full-runtime link or module-data packaging.
  // The executable under analysis is temporary and is never delivered.
  try { requireAotApplication(requirements); }
  catch (error) {
    if (error.code !== 'ERR_LASM_UNSUPPORTED_RUNTIME_FEATURE') throw error;
    try { explainRejection(); } catch { /* the rejection itself is reported */ }
    requireAotApplication(requirements, { explanation: rejectionExplanation({ requirements, whyExtractFile, objects, runtime,
      nm: join(sdk.prefix, 'bin', executableName('llvm-nm')) }) });
  }
  if (!delivered) {
    // The lookup marker is dead. Omit its object from the final link so no
    // delivered executable contains a null implementation of dynamic lookup.
    // (A seeded dev link keeps it: had it survived, the check above rejected the build.)
    await finalLink(planInputs);
    const finalRequirements = await readApplicationLinkRequirements(finalMap, analysis);
    requireAotApplication(finalRequirements);
  }
  // The seed for the next build: the plan, and after a dev build's full link
  // the runtime members it kept and its imports (the fast link's reference).
  if (initializationSeed && seedOut) {
    try {
      if (profile === 'dev' && nodeLink && !debug) {
        if (fullLinked && statSync(finalMap).size < 64 * 1024 * 1024) {
          const imports = wasmImports(join(dist, 'program.wasm'));
          try { if (imports) Object.assign(seedOut, { liveMembers: liveMembers(readFileSync(finalMap, 'utf8'), runtimeArchives), [importsKey]: imports }); }
          catch { /* no fast link next time */ }
        } else if (!fullLinked && fastMembers) Object.assign(seedOut, { liveMembers: fastMembers.liveMembers, [importsKey]: fastMembers[importsKey] });
      }
      if (seedRecord?.probes) seedOut.probes = { ...seedRecord.probes, ...seedOut.probes };
      // The other link kind's import record stays valid while the member set is the same.
      for (const key of ['imports', 'importsLinked'])
        if (!(key in seedOut) && seedRecord?.[key] && JSON.stringify(seedRecord.liveMembers) === JSON.stringify(seedOut.liveMembers)) seedOut[key] = seedRecord[key];
      writeFileSync(initializationSeed, JSON.stringify({ schema: 1, runtime: runtime.identity, ...seedOut }) + '\n');
    } catch { /* an unwritable seed only costs the next dev build its planning */ }
  }
  // Keep only this build's objects; the cache never grows across edits.
  if (objectCache) for (const name of readdirSync(objectCache))
    if (!usedObjects.has(join(objectCache, name))) rmSync(join(objectCache, name), { force: true });
  if (sharedCache) pruneSharedStore(sharedStore, sharedUsed);
  if (linkOnly) return requirements;
  progress?.({ stage: 'Preparing the application launcher' });
  const glue = join(dist, 'program.cjs');
  writeFileSync(glue, connectLeanSymbolLoader(relabelPreJs(readFileSync(glue, 'utf8'), preJs), true, { packageSymbols: true }));
  await indexFunctionTable(join(dist, 'program.wasm'), glue);
  if (!process.env.LASM_LINK_DEBUG) writeFileSync(glue, optimizeMainTableGrowth(readFileSync(glue, 'utf8')));
  writeFileSync(glue, configurableThreadPool(readFileSync(glue, 'utf8')));
  return requirements;
}
