// The compact runtime-initialization wrappers of the edge and browser link
// (docs/BROWSER.md, size). The Node build plans which module initializers run
// (src/application-initialization.mjs) and wraps every initializer in the
// program's import closure: a skipped one calls, in order, the wrappers of the
// initializers it would have called. A small program keeps a handful of
// thousands (6 of 2,807 for the web template), yet links every chain:
// hundreds of KiB of Wasm. From the same plan (initialization-plan.json in the
// Node build's link work) this generates the equivalent with no chains:
//   - each skipped initializer's wrapper is an alias of one no-op;
//   - each kept initializer's wrapper first runs the kept initializers it would
//     have reached (a depth-first walk of the original call order, through kept
//     and skipped initializers alike, in post-order), then its own body.
// Every kept initializer still runs exactly once, after those it depends on and
// in the order the chains ran them; the Node build's own wrappers are unchanged.

/** Kept initializers reachable from `name`'s calls, in the order the original chains initialize them. */
export function initializationSchedule(name, calls, keep) {
  const seen = new Set([name]), order = [];
  const visit = unit => {
    if (seen.has(unit)) return;
    seen.add(unit);
    for (const call of calls[unit] ?? []) visit(call);
    if (keep.has(unit)) order.push(unit);
  };
  for (const call of calls[name] ?? []) visit(call);
  return order;
}

/** C source of the compact wrappers for an initialization plan. */
export function compactInitializerWrappers(plan) {
  if (plan?.schema !== 1 || !Array.isArray(plan.closure) || !Array.isArray(plan.keep) || typeof plan.calls !== 'object') throw new Error('Unrecognized initialization plan');
  const keep = new Set(plan.keep);
  const valid = name => /^(?:runtime_|meta_)?initialize_[A-Za-z0-9_]+$/.test(name);
  for (const name of plan.closure) if (!valid(name)) throw new Error(`Unexpected initializer name ${name}`);
  const lines = ['// Generated by Lasm: compact runtime initialization (src/edge/edge-initializers.mjs).',
    '#include <lean/lean.h>', '#include <stdbool.h>',
    'lean_object* lasm_initializer_skip(uint8_t builtin) { (void)builtin; return lean_io_result_mk_ok(lean_box(0)); }'];
  for (const name of plan.closure) {
    if (!keep.has(name)) { lines.push(`lean_object* __wrap_${name}(uint8_t) __attribute__((alias("lasm_initializer_skip")));`); continue; }
    lines.push(`lean_object* __real_${name}(uint8_t);`, `lean_object* __wrap_${name}(uint8_t);`);
  }
  for (const name of plan.closure.filter(unit => keep.has(unit))) {
    const body = [`lean_object* __wrap_${name}(uint8_t builtin) {`, '  static bool done = false;',
      '  if (done) return lean_io_result_mk_ok(lean_box(0));', '  done = true;'];
    const schedule = initializationSchedule(name, plan.calls, keep);
    if (schedule.length) body.push('  lean_object* res;');
    for (const unit of schedule)
      body.push(`  res = __wrap_${unit}(builtin); if (lean_io_result_is_error(res)) return res; lean_dec_ref(res);`);
    body.push(`  return __real_${name}(builtin);`, '}');
    lines.push(body.join('\n'));
  }
  return lines.join('\n') + '\n';
}
