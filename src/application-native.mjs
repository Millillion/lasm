// C code that Lake packages bundle (extern_lib, moreLinkObjs) for Node.
//
// Lake builds a package's C sources natively first (they are needed during
// elaboration by precompiled modules, and natively Lake links them into the
// executable). Lake 4.35 records every compilation in the output's `.trace`
// file: the command it ran and the source file it hashed. Lasm recompiles each
// recorded source for Wasm with its managed clang, keeping only the
// preprocessor options (include paths, macro definitions, language standard);
// code generation follows Lasm's own recorded flags. Static libraries are read
// from their traces as the list of objects Lake archived. Prebuilt libraries
// (shared libraries, -l options) cannot be compiled and are reported by name.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { isAbsolute, join, resolve, sep } from 'node:path';

// Options whose value may follow as a separate argument.
const valueOptions = new Set(['-I', '-isystem', '-iquote', '-idirafter', '-include', '-imacros', '-D', '-U', '-o', '-MF', '-MT', '-MQ',
  '-x', '-target', '--sysroot', '-arch', '-Xclang', '-Xlinker', '-L', '-l', '-isysroot', '-std', '-mllvm']);
const pathOptions = new Set(['-I', '-isystem', '-iquote', '-idirafter', '-include', '-imacros']);
// System libraries Emscripten provides as part of its C library.
const providedLibraries = new Set(['m', 'c', 'pthread', 'dl', 'rt']);

// Package C code that calls dlopen gets Lasm's always-failing implementation
// (no dynamic loading in Node applications). Lean's own runtime keeps the real
// symbols, which the application policy rejects when reachable.
export const dynamicLoadingRenames = ['dlopen', 'dlsym', 'dlerror', 'dlclose'].map(name => `-D${name}=lasm_package_${name}`);
export const dynamicLoadingStubs = `// Generated by Lasm (src/application-native.mjs).
#include <stddef.h>
static char lasm_package_dl_message[] = "dynamic loading is not available in Node applications built by Lasm";
static int lasm_package_dl_failed;
void *lasm_package_dlopen(const char *file, int mode) { (void)file; (void)mode; lasm_package_dl_failed = 1; return NULL; }
void *lasm_package_dlsym(void *handle, const char *name) { (void)handle; (void)name; lasm_package_dl_failed = 1; return NULL; }
char *lasm_package_dlerror(void) { if (!lasm_package_dl_failed) return NULL; lasm_package_dl_failed = 0; return lasm_package_dl_message; }
int lasm_package_dlclose(void *handle) { (void)handle; return 0; }
`;

const exists = path => { try { statSync(path); return true; } catch { return false; } };

/** Split Lake's logged command arguments (joined by single spaces, unquoted).
 * A path value with spaces is re-joined when the joined path exists. */
export function splitLoggedArguments(text, cwd = process.cwd()) {
  const words = text.split(' ').filter(word => word !== '');
  const result = [];
  for (let index = 0; index < words.length; index++) {
    let word = words[index];
    const separate = valueOptions.has(word);
    const joined = !separate && [...pathOptions].find(option => word.startsWith(option) && word.length > option.length);
    if (separate || joined) {
      const option = separate ? word : joined, first = separate ? words[++index] : word.slice(option.length);
      if (first === undefined) { result.push(word); break; }
      let value = first, end = index;
      if (pathOptions.has(option)) {
        // Prefer the longest run of following words that names an existing path.
        for (let next = index + 1, candidate = value; next < words.length && !words[next].startsWith('-'); next++) {
          candidate += ' ' + words[next];
          if (exists(resolve(cwd, candidate))) { value = candidate; end = next; }
        }
      }
      index = end;
      result.push(separate ? option : option + value, ...(separate ? [value] : []));
      continue;
    }
    result.push(word);
  }
  return result;
}

/** Preprocessor options to keep for the Wasm compile, with Lean's headers
 * replaced by the Wasm runtime's and Lean's compiler-internal paths dropped. */
const leanPrefixes = new Map();
/** The Lean installation containing `path` (it has include/lean/lean.h), if any. */
export function otherLeanPrefix(path) {
  for (let directory = path, depth = 0; depth < 8; depth++) {
    if (!leanPrefixes.has(directory)) leanPrefixes.set(directory, existsSync(join(directory, 'include', 'lean', 'lean.h')));
    if (leanPrefixes.get(directory)) return directory;
    const parent = resolve(directory, '..');
    if (parent === directory) break;
    directory = parent;
  }
  return undefined;
}

export function preprocessorArguments(args, { leanPrefix, runtimeInclude, cwd }) {
  const kept = [], dropped = [];
  // Windows runs Lean from a short execution prefix as well as its installed one.
  const key = path => process.platform === 'win32' ? path.replaceAll('/', '\\').toLowerCase() : path;
  const prefixes = [leanPrefix].flat().filter(Boolean).map(prefix => key(resolve(prefix)));
  const mapPath = value => {
    const path = key(resolve(cwd, value));
    if (prefixes.some(prefix => path === key(resolve(prefix, 'include')))) return runtimeInclude;
    if (prefixes.some(prefix => (path + sep).startsWith(prefix + sep))) return undefined;
    // Lake may reuse objects that another Lean toolchain built in the same
    // project (for example a native `lake build` with elan's Lean): its record
    // then names that toolchain. Any Lean installation is recognized by its
    // include/lean/lean.h; its headers are never used for Wasm.
    const other = otherLeanPrefix(resolve(cwd, value));
    if (other !== undefined) return key(resolve(cwd, value)) === key(join(other, 'include')) ? runtimeInclude : undefined;
    return isAbsolute(value) ? value : resolve(cwd, value);
  };
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    const option = [...pathOptions].find(name => arg === name || arg.startsWith(name) && name !== '-include' && name !== '-imacros');
    if (option) {
      const value = arg === option ? args[++index] : arg.slice(option.length);
      const mapped = mapPath(value);
      // A package's own include directories come after the Wasm C library's, so a
      // native-only stand-in header (MD4Lean's Windows adhoc_include) cannot hide it.
      if (mapped === runtimeInclude) kept.push('-I', mapped);
      else if (mapped) kept.push(option === '-I' || option === '-iquote' || option === '-isystem' ? '-idirafter' : option, mapped);
      else dropped.push(arg, ...(arg === option ? [value] : []));
    } else if (arg === '-D' || arg === '-U') kept.push(arg + args[++index]);
    else if (/^-[DU]./.test(arg) || /^-std=/.test(arg)) kept.push(arg);
    else if (valueOptions.has(arg)) dropped.push(arg, args[++index]);
    else dropped.push(arg);
  }
  return { kept, dropped };
}

const readTrace = file => {
  try { return JSON.parse(readFileSync(file + '.trace', 'utf8')); }
  catch (error) { if (error.code === 'ENOENT') return undefined; throw error; }
};

/** Lake's record of how `object` was compiled: the C source and its arguments. */
export function recordedCompilation(object) {
  const trace = readTrace(object);
  if (!trace) throw new Error(`Lake has no build record for ${object}; Lasm cannot compile it for Node. Build it with a Lake target (buildO, compileO, buildLeanO).`);
  const source = trace.inputs?.find(input => Array.isArray(input) && typeof input[0] === 'string' && /\.(?:c|cc|cpp|cxx|C)$/.test(input[0]))?.[0];
  const marker = ` -c -o ${object} `;
  for (const { message } of trace.log ?? []) {
    if (typeof message !== 'string') continue;
    const prompt = message.indexOf('> '), at = message.indexOf(marker);
    if (prompt < 0 || at < 0) continue;
    const rest = message.slice(at + marker.length);
    const sourcePath = source && rest.startsWith(source) ? source : rest.split(' ')[0];
    const cwd = message.slice(0, prompt);
    return { object, source: sourcePath, cwd: cwd === '.' ? process.cwd() : cwd,
      compiler: message.slice(prompt + 2, at).trim().split(' ').pop(), args: rest.slice(sourcePath.length).trim(),
      language: /\.(?:cc|cpp|cxx|C)$/.test(sourcePath) ? 'c++' : 'c', identity: createHash('sha256').update(JSON.stringify(trace)).digest('hex') };
  }
  throw new Error(`Lake's build record for ${object} does not show how it was compiled; Lasm cannot compile it for Node.`);
}

/** Objects that Lake archived into a static library, from its trace. */
export function archivedObjects(library) {
  const trace = readTrace(library);
  const objs = trace?.inputs?.find(input => Array.isArray(input) && input[0] === 'objs')?.[1];
  if (!Array.isArray(objs)) throw new Error(`Lake has no build record for the static library ${library}; Lasm cannot compile it for Node.`);
  return objs.map(entry => entry[0]);
}

const knownLibraries = [
  [/^(?:curl)$/, 'libcurl (HTTP client)', 'Use the Fetch package (Node fetch backend) or run the curl command with IO.Process.'],
  [/^(?:ssl|crypto|libssl|libcrypto)$/, 'OpenSSL', 'Node-backed cryptography is a follow-up candidate.'],
  [/^(?:pq|libpq)$/, 'libpq (PostgreSQL client)', 'A pure-Lean or Node-backed PostgreSQL client is a follow-up candidate.'],
  [/^(?:hiredis)$/, 'hiredis (Redis client)', 'Use a pure-Lean Redis client (for example lean-redis).'],
  [/^(?:blas|cblas|openblas|lapack)$/, 'BLAS/LAPACK', 'No Wasm BLAS is provided.'],
  [/^(?:sqlite3)$/, 'system SQLite', 'Use leansqlite, which bundles SQLite as C source.'],
  [/^(?:z|zlib)$/, 'zlib', 'Use lean-zip (pure Lean) or Node\'s zlib.'],
  [/^(?:gmp|libgmp)$/, 'GNU MP', "Lasm's runtime uses Lean's own big-number code (no GMP); use Lean's Nat and Int."],
];
/** A readable description of a prebuilt library that cannot be linked. */
export function describeLibrary(name) {
  const base = name.replace(/,.*$/, '').replace(/^.*[\\/]/, '').replace(/^lib/, '').replace(/\.(?:so(?:\.\d+)*|dylib|dll|a|lib)$/, '');
  const known = knownLibraries.find(([pattern]) => pattern.test(base));
  return known ? { name: base, label: known[1], advice: known[2] } : { name: base, label: `the native library ${base}`, advice: '' };
}

export class UnsupportedNativeLibrary extends Error {
  constructor(entries, symbols = []) {
    const lines = entries.map(({ package: pkg, library, reason }) => {
      const owner = pkg ? `package ${pkg}` : 'the program';
      if (/^does not compile/.test(reason ?? '')) return `  ${owner} has C code (${library}) that ${reason}`;
      const { label, advice } = describeLibrary(library);
      return `  ${owner} links ${label} (${library})${reason && !/^(?:prebuilt|shared)/.test(reason) ? ` [${reason}]` : ''}${advice ? '. ' + advice : ''}`;
    });
    super([`Lasm cannot link prebuilt native libraries into a Node application${symbols.length ? `; the program needs ${symbols.slice(0, 6).join(', ')}` : ''}:`,
      ...lines, 'Lasm compiles C source that packages bundle and that Lake compiles (extern_lib, moreLinkObjs); prebuilt system or shared libraries are not available in Wasm.',
      'See "Lean support and restrictions" in the Lasm README.'].join('\n'));
    this.name = 'UnsupportedNativeLibrary'; this.code = 'ERR_LASM_NATIVE_LIBRARY'; this.libraries = entries;
  }
}

/** Plan the Wasm compilation of a Lake program's native link inputs
 * (src/lake-module.lean --link). Prebuilt libraries and objects Lake has no
 * compile record for cannot be compiled; they are listed as unavailable and
 * matter only when the program's code actually reaches their symbols. */
export function planNativeInputs(info, { leanPrefix, runtimeInclude }) {
  const unavailable = [];
  for (const lib of info.libs ?? []) unavailable.push({ library: lib.path || lib.name, reason: 'shared library' });
  for (const { package: pkg, arg } of info.args ?? []) {
    const library = /^-l(.+)$/.exec(arg)?.[1] ?? (/\.(?:so(?:\.\d+)*|dylib|dll)$/.test(arg) ? arg : undefined);
    if (library && !providedLibraries.has(library)) unavailable.push({ package: pkg, library, reason: 'prebuilt library' });
  }
  const compilations = [];
  for (const entry of info.objs ?? []) {
    const { package: pkg, path: file } = typeof entry === 'string' ? { path: entry } : entry;
    if (/\.(?:so(?:\.\d+)*|dylib|dll)$/.test(file)) { unavailable.push({ package: pkg, library: file, reason: 'shared library' }); continue; }
    let objects;
    try { objects = /\.(?:a|lib)$/.test(file) ? archivedObjects(file) : [file]; }
    catch (error) { unavailable.push({ package: pkg, library: file, reason: error.message }); continue; }
    for (const object of objects) {
      let record;
      try { record = recordedCompilation(object); }
      catch (error) { unavailable.push({ package: pkg, library: file, reason: error.message }); continue; }
      const args = preprocessorArguments(splitLoggedArguments(record.args, record.cwd), { leanPrefix, runtimeInclude, cwd: record.cwd });
      const source = isAbsolute(record.source) ? record.source : join(record.cwd, record.source);
      if (!existsSync(source)) { unavailable.push({ package: pkg, library: file, reason: `its C source ${source} is missing` }); continue; }
      compilations.push({ ...record, package: pkg, source, extraArgs: [...args.kept, ...dynamicLoadingRenames], droppedArgs: args.dropped });
    }
  }
  const seen = new Set();
  return { compilations, unavailable: unavailable.filter(item => {
    const key = `${item.package}\0${item.library}`;
    return !seen.has(key) && seen.add(key);
  }) };
}

// Undefined-symbol prefixes of common prebuilt libraries, for link failures.
const symbolLibraries = [[/^curl_/, 'curl'], [/^(?:SSL_|SSL_CTX_|EVP_|OPENSSL_|BIO_|X509_|CRYPTO_|RAND_bytes|ERR_get_error)/, 'ssl'],
  [/^PQ/, 'pq'], [/^redis/, 'hiredis'], [/^(?:cblas_|dgemm_|sgemm_|LAPACKE_)/, 'blas'], [/^sqlite3_/, 'sqlite3'],
  [/^(?:deflate|inflate|compress2?|uncompress)(?:Init|End|$)/, 'z'],
  // Lasm's runtime uses Lean's own big-number code (USE_GMP=OFF, docs/PLAN.md
  // decision 5): GMP's API and Lean's GMP-only lean_alloc_mpz/lean_extract_mpz_value
  // are not available to native code.
  [/^(?:__gmp[zqnf]?_|lean_alloc_mpz$|lean_extract_mpz_value$)/, 'gmp']];
/** Undefined symbols reported by a failed link. */
export const undefinedSymbols = output => [...new Set([...String(output).matchAll(/undefined symbol: ([A-Za-z_][A-Za-z0-9_]*)/g)].map(match => match[1]))];

/** The prebuilt libraries a failed link's undefined symbols point to. */
export function librariesForUndefinedSymbols(output) {
  const found = new Map();
  for (const match of String(output).matchAll(/undefined symbol: ([A-Za-z_][A-Za-z0-9_]*)/g))
    for (const [pattern, library] of symbolLibraries) if (pattern.test(match[1]) && !found.has(library)) found.set(library, match[1]);
  return [...found].map(([library, symbol]) => ({ library, symbol }));
}
