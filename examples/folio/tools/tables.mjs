// Generates Folio/Tables.lean: the Unicode and HTML data the CommonMark
// renderer needs, taken from the same sources commonmark.js 0.31.2 uses so
// that the two agree character for character:
//
// - punctuation: ASCII punctuation and the Unicode general categories P and
//   S (CommonMark 0.31.2, "Unicode punctuation character"), as the regular
//   expression in commonmark.js's inlines.js matches them;
// - case folding for link labels: commonmark.js normalizes a label with
//   `.toLowerCase().toUpperCase()`; the table records every code point that
//   this changes, and what it becomes;
// - named character references: the HTML5 entity list, decoded with
//   `decodeHTMLStrict` from the `entities` package commonmark.js uses.
//
// Unicode data comes from the Node.js that runs this script (its ICU); the
// version is written into the generated file. Run:
//   node tools/tables.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { decodeHTMLStrict } = require('entities');
const names = Object.keys(JSON.parse(readFileSync(require.resolve('entities/lib/maps/entities.json'), 'utf8')));

const hex = n => n.toString(16).toUpperCase();
const cps = s => [...s].map(c => hex(c.codePointAt(0))).join(',');
const rePunctuation = /^[!"#$%&'()*+,\-./:;<=>?@\[\]\\^_`{|}~\p{P}\p{S}]/u;

const ranges = [];
const cases = [];
for (let c = 0; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const s = String.fromCodePoint(c);
  if (rePunctuation.test(s)) {
    const last = ranges[ranges.length - 1];
    if (last && last[1] === c - 1) last[1] = c; else ranges.push([c, c]);
  }
  const folded = s.toLowerCase().toUpperCase();
  if (folded !== s) cases.push(`${hex(c)} ${cps(folded)}`);
}

const entities = [];
for (const name of [...new Set(names)].sort()) {
  if (!/^[a-z][a-z0-9]{1,31}$/i.test(name)) continue;
  const value = decodeHTMLStrict(`&${name};`);
  if (value === `&${name};`) continue;
  entities.push(`${name} ${cps(value)}`);
}

const lean = `/-
Generated by \`node tools/tables.mjs\` (Node.js ${process.versions.node}, Unicode ${process.versions.unicode}); do not edit by hand.

The data CommonMark needs from Unicode and HTML, from the same sources as
commonmark.js 0.31.2 (see tools/tables.mjs). The HTML5 entity names come
from the \`entities\` package (BSD-2-Clause, Felix Böhm), which takes them
from the WHATWG HTML Standard.
-/
namespace Folio.Tables

/-- Code point ranges \`lo hi\` (hexadecimal) of the characters CommonMark
counts as punctuation: ASCII punctuation and Unicode categories P and S. -/
def punctuationData : String :=
  "${ranges.map(([a, b]) => `${hex(a)} ${hex(b)}`).join('\\n')}"

/-- \`c f₁,f₂,…\`: \`String.fromCodePoint(c).toLowerCase().toUpperCase()\`,
for every code point that it changes (link-label case folding). -/
def caseData : String :=
  "${cases.join('\\n')}"

/-- \`name c₁,c₂,…\`: each HTML5 named character reference (without \`&\`
and \`;\`) and the code points it stands for. -/
def entityData : String :=
  "${entities.join('\\n')}"

end Folio.Tables
`;
writeFileSync(new URL('../Folio/Tables.lean', import.meta.url), lean);
console.log(`${ranges.length} punctuation ranges, ${cases.length} case mappings, ${entities.length} entities`);
