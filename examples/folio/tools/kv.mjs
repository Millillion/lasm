// The site's files as the entries of the edge server's key-value store
// (ServerEdge.lean): each file of the site's directory (index.md,
// content/**/*.md, layouts/*.html) under its path, and `files`, the list of
// those paths, one per line.
//
//   node tools/kv.mjs json [SITE] > kv.json      # Workers KV: wrangler kv bulk put kv.json --binding folio [--local]
//   node tools/kv.mjs fastly [SITE] > fastly.toml # Viceroy's local KV Store, in fastly.toml
//   deno run -A --unstable-kv tools/kv.mjs deno [SITE] [DATABASE]
//                                                 # Deno KV: Deno.openKv(DATABASE), else the default database
//
// SITE defaults to site/. Runs on Node and Deno.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The store's name (ServerEdge.lean's `storeName`). */
export const storeName = 'folio';

/** The store's entries for the site in `dir`: [{ key, value }], `files` last. */
export function entries(dir) {
  const paths = [];
  const walk = d => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else paths.push(relative(dir, p).split(sep).join('/'));
    }
  };
  walk(dir);
  const site = paths.filter(p => p === 'index.md' || (p.startsWith('content/') && p.endsWith('.md')) ||
    (/^layouts\/[^/]+\.html$/.test(p)));
  return [...site.map(key => ({ key, value: readFileSync(join(dir, key), 'utf8') })),
    { key: 'files', value: site.map(p => p + '\n').join('') }];
}

/** fastly.toml for the site in `dir`: the service, and Viceroy's KV Store `folio` holding the site. */
export function fastlyToml(dir) {
  // A JSON string is a TOML basic string (the same escapes: \n, \", \\, \uXXXX),
  // once DEL, which TOML also forbids, is escaped.
  const str = s => JSON.stringify(s).replaceAll('\x7f', '\\u007F');
  const kv = entries(dir).map(e => `  [[local_server.kv_stores.${storeName}]]\n    key = ${str(e.key)}\n    data = ${str(e.value)}\n`).join('');
  return `# Fastly Compute: npm run build:fastly writes bin/main.wasm and pkg/folio.tar.gz.
# Locally: viceroy serve -C fastly.toml bin/main.wasm (or fastly compute serve),
# with the KV Store below. To deploy (fastly compute deploy), create a KV Store
# named folio, link it to the service and put the site's files in it
# (node tools/kv.mjs json lists the entries). Generated by
# node tools/kv.mjs fastly > fastly.toml from site/.
manifest_version = 3
name = "folio"
description = "Folio, a CommonMark site generator in Lean, serving a site from a KV Store"
authors = []
language = "other"

[scripts]
build = "npm run build:fastly"

[local_server]
  [local_server.kv_stores]
${kv}`;
}

if (import.meta.main ?? process.argv[1] === fileURLToPath(import.meta.url)) {
  const [command, site = fileURLToPath(new URL('../site', import.meta.url)), database] = process.argv.slice(2);
  if (command === 'json') console.log(JSON.stringify(entries(site), null, 2));
  else if (command === 'fastly') process.stdout.write(fastlyToml(site));
  else if (command === 'deno') {
    const kv = await globalThis.Deno.openKv(database);
    for await (const e of kv.list({ prefix: [storeName] })) await kv.delete(e.key);
    for (const e of entries(site)) await kv.set([storeName, e.key], e.value);
    kv.close();
    console.error(`Deno KV: ${entries(site).length} entries under ["${storeName}", …]`);
  } else {
    console.error('usage: node tools/kv.mjs json|fastly [SITE], or deno run -A --unstable-kv tools/kv.mjs deno [SITE] [DATABASE]');
    process.exitCode = 2;
  }
}
