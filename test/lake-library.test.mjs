// Lasm's library as a Lake package (src/lake-library.mjs, decision 0.3-7): the package per prefix, the eager
// library files linked into its build directory (idempotent, stale ones replaced), the project's link, and the
// lakefile's require.
import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readlinkSync, realpathSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { addLakeRequire, ensureLakeLibrary, ensureLakePackage, ensureProjectLink, lakeLinkPath, lakePackageDirectory, lakePackageLakefile,
  lakeRequireLean, lakeRequireToml, lakefileOf, requiresLakePackage } from '../src/lake-library.mjs';

const put = (file, text) => { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, text); };
/** A library root (eager Core, lazy A and B), a prefix holding Core's .olean, a cache and a project. */
function fixture() {
  const dir = mkdtempSync(join(tmpdir(), 'lasm-lake-'));
  const root = join(dir, 'library'), prefix = join(dir, 'prefix'), cache = join(dir, 'cache'), project = join(dir, 'app');
  put(join(root, 'Lasm/JS/Web/Core.lean'), 'import Lasm.JS\n');
  put(join(root, 'Lasm/JS/Web/A.lean'), 'import Lasm.JS.Web.Core\n');
  put(join(root, 'Lasm/JS/Web/B.lean'), 'import Lasm.JS.Web.A\n');
  put(join(prefix, 'lib/lean/Lasm/JS.olean'), 'olean of Lasm.JS');
  put(join(prefix, 'lib/lean/Lasm/JS/Web/Core.olean'), 'olean of Core');
  put(join(project, 'lakefile.toml'), 'name = "app"\n');
  return { dir, root, prefix, cache, project, eager: ['Lasm.JS', 'Lasm.JS.Web.Core'] };
}
const built = (directory, module) => join(directory, '.lake/build/lib/lean', ...module.split('.')) + '.olean';

test('the package: a lakefile whose library roots are the lazily compiled modules, from the library sources', () => {
  const text = lakePackageLakefile({ root: '/lib/rary', lazy: ['Lasm.JS.Web.A', 'Lasm.JS.Web.B'], version: '9.9.9' });
  assert.match(text, /^# Generated by Lasm 9\.9\.9 /);
  assert.match(text, /^name = "lasm"$/m);
  assert.match(text, /^srcDir = "\/lib\/rary"$/m);
  assert.match(text, /^roots = \["Lasm\.JS\.Web\.A", "Lasm\.JS\.Web\.B"\]$/m);
  // Windows paths are written with forward slashes, which TOML needs no escapes for.
  assert.match(lakePackageLakefile({ root: 'C:\\Users\\me\\lib', lazy: [] }), /^srcDir = "C:\/Users\/me\/lib"$/m);
  // One directory per prefix and library.
  assert.notEqual(lakePackageDirectory('/p1', { cache: '/c', root: '/r' }), lakePackageDirectory('/p2', { cache: '/c', root: '/r' }));
  assert.notEqual(lakePackageDirectory('/p1', { cache: '/c', root: '/r1' }), lakePackageDirectory('/p1', { cache: '/c', root: '/r2' }));
  assert.equal(lakePackageDirectory('/p1', { cache: '/c', root: '/r' }), lakePackageDirectory('/p1', { cache: '/c', root: '/r' }));
});

test('the eager library files are linked into the build directory once, and replaced when stale', () => {
  const { dir, root, prefix, cache, eager } = fixture();
  try {
    const directory = ensureLakePackage(prefix, { eager, cache, root });
    assert.match(readFileSync(join(directory, 'lakefile.toml'), 'utf8'), /roots = \["Lasm\.JS\.Web\.A", "Lasm\.JS\.Web\.B"\]/);
    assert.equal(JSON.parse(readFileSync(join(directory, 'lake-manifest.json'), 'utf8')).name, 'lasm');
    for (const module of eager) assert.equal(readFileSync(built(directory, module), 'utf8'), readFileSync(join(prefix, 'lib/lean', ...module.split('.')) + '.olean', 'utf8'));
    assert.ok(!existsSync(built(directory, 'Lasm.JS.Web.A')), 'Lake builds the lazy modules');
    // Again: nothing changes.
    const before = statSync(built(directory, 'Lasm.JS')).mtimeMs, receipt = readFileSync(join(directory, 'lasm-package.json'), 'utf8');
    assert.equal(ensureLakePackage(prefix, { eager, cache, root }), directory);
    assert.equal(statSync(built(directory, 'Lasm.JS')).mtimeMs, before);
    assert.equal(readFileSync(join(directory, 'lasm-package.json'), 'utf8'), receipt);
    // A changed file (a stale copy, another Lasm's library) is replaced.
    writeFileSync(join(prefix, 'lib/lean/Lasm/JS.olean'), 'olean of a newer Lasm.JS');
    ensureLakePackage(prefix, { eager, cache, root });
    assert.equal(readFileSync(built(directory, 'Lasm.JS'), 'utf8'), 'olean of a newer Lasm.JS');
    rmSync(built(directory, 'Lasm.JS.Web.Core'));
    ensureLakePackage(prefix, { eager, cache, root });
    assert.equal(readFileSync(built(directory, 'Lasm.JS.Web.Core'), 'utf8'), 'olean of Core');
    // A module that is no longer eager (an older receipt) goes, and the lakefile follows the new roots.
    ensureLakePackage(prefix, { eager: ['Lasm.JS'], cache, root });
    assert.ok(!existsSync(built(directory, 'Lasm.JS.Web.Core')));
    assert.match(readFileSync(join(directory, 'lakefile.toml'), 'utf8'), /roots = \["Lasm\.JS\.Web\.A", "Lasm\.JS\.Web\.B", "Lasm\.JS\.Web\.Core"\]/);
    // An edited lakefile is rewritten.
    writeFileSync(join(directory, 'lakefile.toml'), 'name = "lasm"\n');
    ensureLakePackage(prefix, { eager: ['Lasm.JS'], cache, root });
    assert.match(readFileSync(join(directory, 'lakefile.toml'), 'utf8'), /roots = /);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('the project link: made, kept, repointed, and a directory in its place replaced without touching the package', () => {
  const { dir, root, prefix, cache, project, eager } = fixture();
  try {
    const one = ensureLakePackage(prefix, { eager, cache, root });
    assert.deepEqual(ensureProjectLink(project, one), { link: lakeLinkPath(project), changed: true });
    assert.ok(lstatSync(lakeLinkPath(project)).isSymbolicLink());
    assert.equal(realpathSync(lakeLinkPath(project)), realpathSync(one));
    assert.equal(ensureProjectLink(project, one).changed, false);
    // Another prefix (the C tier): the link moves; the old package stays whole.
    const prefix2 = join(dir, 'prefix2');
    put(join(prefix2, 'lib/lean/Lasm/JS.olean'), 'olean 2');
    const two = ensureLakePackage(prefix2, { eager, cache, root });
    assert.equal(ensureProjectLink(project, two).changed, true);
    assert.equal(realpathSync(lakeLinkPath(project)), realpathSync(two));
    assert.ok(existsSync(join(one, 'lakefile.toml')), 'unlinking never deletes the target');
    // A broken link, then a real directory (a copy), are replaced.
    rmSync(lakeLinkPath(project));
    symlinkSync(join(dir, 'missing'), lakeLinkPath(project));
    assert.equal(ensureProjectLink(project, one).changed, true);
    assert.equal(realpathSync(lakeLinkPath(project)), realpathSync(one));
    rmSync(lakeLinkPath(project));
    put(join(lakeLinkPath(project), 'lakefile.toml'), 'name = "lasm"\n');
    assert.equal(ensureProjectLink(project, one).changed, true);
    assert.ok(readlinkSync(lakeLinkPath(project)));
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('the lakefile require: detected and added once, in TOML and Lean configurations', () => {
  const { dir, project } = fixture();
  try {
    assert.equal(lakefileOf(project), join(project, 'lakefile.toml'));
    assert.equal(requiresLakePackage(project), false);
    assert.equal(addLakeRequire(project), true);
    assert.equal(readFileSync(join(project, 'lakefile.toml'), 'utf8'), `name = "app"\n\n${lakeRequireToml}`);
    assert.equal(requiresLakePackage(project), true);
    assert.equal(addLakeRequire(project), false);
    // Another package's require is not ours.
    writeFileSync(join(project, 'lakefile.toml'), 'name = "app"\n\n[[require]]\nname = "batteries"\n\n[[lean_lib]]\nname = "lasm"\n');
    assert.equal(requiresLakePackage(project), false);
    rmSync(join(project, 'lakefile.toml'));
    writeFileSync(join(project, 'lakefile.lean'), 'import Lake\nopen Lake DSL\npackage app');
    assert.equal(addLakeRequire(project), true);
    assert.equal(readFileSync(join(project, 'lakefile.lean'), 'utf8'), `import Lake\nopen Lake DSL\npackage app\n\n${lakeRequireLean}`);
    assert.equal(requiresLakePackage(project), true);
    rmSync(join(project, 'lakefile.lean'));
    assert.equal(lakefileOf(project), undefined);
    assert.equal(addLakeRequire(project), false);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('every lasm command\'s step: the package, the link, and whether Lake builds the modules', () => {
  const { dir, prefix, cache, project, eager } = fixture();
  try {
    // The real library root (the default): every lazily compiled module of the shipped library is a root.
    const first = ensureLakeLibrary(project, prefix, { eager, cache });
    assert.deepEqual(first, { required: false, directory: lakePackageDirectory(prefix, { cache }) });
    assert.match(readFileSync(join(lakeLinkPath(project), 'lakefile.toml'), 'utf8'), /"Lasm\.JS\.Web\.IndexedDB"/);
    addLakeRequire(project);
    assert.equal(ensureLakeLibrary(project, prefix, { eager, cache }).required, true);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
