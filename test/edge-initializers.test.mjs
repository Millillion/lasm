// The compact initializer wrappers of the edge and browser links
// (src/edge/edge-initializers.mjs). The generated C is read back by a strict
// interpreter of exactly the lines the generator writes, and run: for random
// initializer graphs and plans, the kept initializers run as the Node build's
// chains run them (each once, after those it reaches, in the chains' order).
import test from 'node:test';
import assert from 'node:assert/strict';
import { initializationSchedule, compactInitializerWrappers } from '../src/edge/edge-initializers.mjs';
import { forAll } from './helpers/property.mjs';

/** A random initializer graph: names, the calls of each (in order), the kept set. */
function plan(g, { acyclic = g.next() < 0.5 } = {}) {
  const prefixes = ['initialize_', 'runtime_initialize_', 'meta_initialize_'];
  const names = g.array(g.int(1, 14), (_, i) => `${g.pick(prefixes)}M${i}_${g.string('abcXYZ019_', 0, 4)}`);
  const calls = {};
  for (const [i, name] of names.entries()) {
    const targets = names.filter((_, j) => acyclic ? j > i : true);
    const list = g.array(g.int(0, Math.min(4, targets.length)), () => g.pick(targets.length ? targets : [name]));
    if (list.length || g.next() < 0.5) calls[name] = [...new Set(list)];
  }
  const keep = names.filter(() => g.next() < 0.5);
  return { schema: 1, closure: names, keep, calls };
}

/** The Node build's chains: each wrapper runs once, calling its imports' wrappers, then (when kept) its body. */
function chains(p, entries) {
  const done = new Set(), ran = [], keep = new Set(p.keep);
  const run = name => {
    if (done.has(name)) return;
    done.add(name);
    for (const call of p.calls[name] ?? []) run(call);
    if (keep.has(name)) ran.push(name);
  };
  for (const entry of entries) run(entry);
  return ran;
}

/** Runs the generated C: the real initializer of a kept unit calls the wrappers of its imports, then records itself. */
function interpret(source, p, entries) {
  const lines = source.split('\n');
  assert.deepEqual(lines.slice(0, 4), ['// Generated by Lasm: compact runtime initialization (src/edge/edge-initializers.mjs).',
    '#include <lean/lean.h>', '#include <stdbool.h>',
    'lean_object* lasm_initializer_skip(uint8_t builtin) { (void)builtin; return lean_io_result_mk_ok(lean_box(0)); }']);
  assert.equal(lines.at(-1), '', 'ends with a newline');
  const aliases = new Set(), declaredReal = new Set(), declaredWrap = new Set(), bodies = new Map();
  for (let i = 4; i < lines.length - 1; i++) {
    const line = lines[i];
    let m;
    if ((m = /^lean_object\* __wrap_(\w+)\(uint8_t\) __attribute__\(\(alias\("lasm_initializer_skip"\)\)\);$/.exec(line))) { aliases.add(m[1]); continue; }
    if ((m = /^lean_object\* __real_(\w+)\(uint8_t\);$/.exec(line))) { declaredReal.add(m[1]); continue; }
    if ((m = /^lean_object\* __wrap_(\w+)\(uint8_t\);$/.exec(line))) { declaredWrap.add(m[1]); continue; }
    m = /^lean_object\* __wrap_(\w+)\(uint8_t builtin\) \{$/.exec(line);
    assert.ok(m, `unexpected line ${JSON.stringify(line)}`);
    const name = m[1];
    assert.deepEqual(lines.slice(i + 1, i + 4), ['  static bool done = false;', '  if (done) return lean_io_result_mk_ok(lean_box(0));', '  done = true;']);
    i += 4;
    const schedule = [];
    if (lines[i] === '  lean_object* res;') i++;
    for (; (m = /^ {2}res = __wrap_(\w+)\(builtin\); if \(lean_io_result_is_error\(res\)\) return res; lean_dec_ref\(res\);$/.exec(lines[i])); i++) schedule.push(m[1]);
    if (schedule.length) assert.equal(lines[i - schedule.length - 1], '  lean_object* res;', 'res is declared before it is used');
    else assert.notEqual(lines[i - 1], '  lean_object* res;', 'and only then');
    assert.equal(lines[i], `  return __real_${name}(builtin);`);
    assert.equal(lines[i + 1], '}');
    i++;
    bodies.set(name, schedule);
  }
  const keep = new Set(p.keep);
  for (const name of p.closure) {
    assert.equal(aliases.has(name), !keep.has(name), `${name}: skipped exactly when not kept`);
    assert.equal(bodies.has(name), keep.has(name), `${name}: defined when kept`);
    assert.equal(declaredReal.has(name), keep.has(name), `${name}: its initializer declared when kept`);
    assert.equal(declaredWrap.has(name), keep.has(name), `${name}: its wrapper declared when kept`);
  }
  const done = new Set(), ran = [];
  const wrap = name => {
    if (aliases.has(name)) return;
    assert.ok(bodies.has(name), `${name} is defined`);
    if (done.has(name)) return;
    done.add(name);
    for (const unit of bodies.get(name)) wrap(unit);
    // __real_: the unit's own initializer, which calls its imports' (wrapped) initializers first.
    for (const call of p.calls[name] ?? []) wrap(call);
    ran.push(name);
  };
  for (const entry of entries) wrap(entry);
  return ran;
}

// Proposition: Lasm.Cli.Candidates.compact_wrappers_as_chains
//  ∀ (p : Plan) (entries : List String), Acyclic p.edges →
//    (∀ x ∈ p.closure, initializerName x = true) → (∀ x, ∀ y ∈ p.edges x, y ∈ p.closure) →
//    (∀ e ∈ entries, e ∈ p.keep) → (∀ k ∈ p.keep, k ∈ p.closure) →
//    ∃ source, compactInitializerWrappers p = .ok source ∧ runInitializers source p.edges entries = chains p entries
test('compact wrappers run the kept initializers exactly as the chains do', () => {
  forAll(g => { const p = plan(g, { acyclic: true }); return { p, entries: p.keep.length ? g.array(g.int(1, 3), () => g.pick(p.keep)) : [] }; }, ({ p, entries }) => {
    const ran = interpret(compactInitializerWrappers(p), p, entries);
    assert.deepEqual(ran, chains(p, entries));
    assert.equal(new Set(ran).size, ran.length, 'each kept initializer once');
  }, { runs: 300 });
});

// Proposition: Lasm.Cli.Spec.schedule_reached_kept_first
//  ∀ (calls : List (String × List String)) (keep : List String) (n : String), Acyclic (edgesOf calls) →
//    (initializationSchedule n calls keep).Nodup ∧
//    (∀ y, y ∈ initializationSchedule n calls keep ↔ y ∈ keep ∧ y ≠ n ∧ Reaches (edgesOf calls) n y) ∧
//    ∀ x ∈ initializationSchedule n calls keep, ∀ y, y ∈ keep → y ≠ n → Reaches (edgesOf calls) x y →
//      (initializationSchedule n calls keep).idxOf y < (initializationSchedule n calls keep).idxOf x
test('initializationSchedule: the kept initializers a unit reaches, each once, those it depends on first', () => {
  forAll(g => plan(g, { acyclic: true }), p => {
    const keep = new Set(p.keep);
    const reach = from => { const seen = new Set(); const walk = u => { for (const c of p.calls[u] ?? []) if (!seen.has(c)) { seen.add(c); walk(c); } }; walk(from); return seen; };
    for (const name of p.closure) {
      const schedule = initializationSchedule(name, p.calls, keep);
      const reached = reach(name);
      assert.deepEqual(new Set(schedule), new Set([...reached].filter(u => keep.has(u) && u !== name)));
      assert.equal(new Set(schedule).size, schedule.length);
      for (const [i, x] of schedule.entries())
        for (const y of reach(x)) if (keep.has(y) && y !== name) assert.ok(schedule.indexOf(y) < i, `${y} before ${x}`);
    }
  }, { runs: 300 });
  // A unit is never in its own schedule, even through a cycle; units without calls have none.
  const keep = new Set(['a', 'b']);
  assert.deepEqual(initializationSchedule('a', { a: ['b'], b: ['a'] }, keep), ['b']);
  assert.deepEqual(initializationSchedule('a', {}, keep), []);
  assert.deepEqual(initializationSchedule('a', { a: ['c'], c: ['b'] }, keep), ['b'], 'through skipped units');
  assert.deepEqual(initializationSchedule('a', { a: ['b', 'c'], c: ['b'] }, new Set(['a', 'b', 'c'])), ['b', 'c']);
});

test('compactInitializerWrappers rejects plans it does not recognize and names that are not initializers', () => {
  const good = { schema: 1, closure: ['initialize_A'], keep: [], calls: {} };
  compactInitializerWrappers(good);
  for (const bad of [null, undefined, { ...good, schema: 2 }, { ...good, closure: 'initialize_A' }, { ...good, keep: new Set() }, { ...good, calls: 'x' }, { ...good, calls: undefined }])
    assert.throws(() => compactInitializerWrappers(bad), { message: 'Unrecognized initialization plan' }, JSON.stringify(bad));
  for (const name of ['initialize_', 'xinitialize_A', 'initialize_A;', 'initialize_A\nint x', 'runtime_meta_initialize_A', 'Initialize_A', 'initialize_A-B'])
    assert.throws(() => compactInitializerWrappers({ ...good, closure: [name] }), { message: `Unexpected initializer name ${name}` });
  for (const name of ['initialize_A', 'runtime_initialize_Lean_9', 'meta_initialize_x_Y'])
    assert.match(compactInitializerWrappers({ ...good, closure: [name] }), new RegExp(`__wrap_${name}\\(uint8_t\\) __attribute__`));
  // Declarations come before definitions, in closure order.
  const text = compactInitializerWrappers({ schema: 1, closure: ['initialize_B', 'initialize_A', 'initialize_C'], keep: ['initialize_A', 'initialize_C'], calls: { initialize_C: ['initialize_A'] } });
  assert.deepEqual(text.split('\n').slice(4, 9), ['lean_object* __wrap_initialize_B(uint8_t) __attribute__((alias("lasm_initializer_skip")));',
    'lean_object* __real_initialize_A(uint8_t);', 'lean_object* __wrap_initialize_A(uint8_t);', 'lean_object* __real_initialize_C(uint8_t);', 'lean_object* __wrap_initialize_C(uint8_t);']);
  assert.ok(text.indexOf('__wrap_initialize_A(uint8_t builtin) {') < text.indexOf('__wrap_initialize_C(uint8_t builtin) {'));
});
