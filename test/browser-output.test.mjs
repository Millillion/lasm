test('bundler: whitespace and punctuation the import and export forms allow', async () => {
  const modules = {
    './e.mjs': [
      "import  *  as  ns  from  './a.mjs';  ",
      "import\tdef\tfrom\t'./b.mjs'",
      "import {  one  as  uno ,  two , } from './a.mjs';",
      'export const run = () => [ns.one, def, uno, two];',
    ].join('\n'),
    './a.mjs': "export  const one = 1;\nexport async  function later() {}\nexport  var two = 2;\nexport{ one as alias }\nexport {  later  as  soon  } ;  \n",
    './b.mjs': 'export  default  3;\n',
  };
  const text = bundleModules(modules, './e.mjs');
  assert.match(text, /return \{ one, later, two, "alias": one, "soon": later \};/);
  const dir = mkdtempSync(join(tmpdir(), 'lasm-bundle-space-'));
  try {
    writeFileSync(join(dir, 'b.mjs'), text);
    const { run } = await import(pathToFileURL(join(dir, 'b.mjs')).href);
    assert.deepEqual(run(), [1, 3, 1, 2]);
  } finally { rmSync(dir, { recursive: true, force: true }); }
  // An external check never sees relative imports, ../ included.
  const seen = [];
  const nested = bundleModules({ './lib/e.mjs': "import { a } from '../a.mjs';\nexport { a };\n", './a.mjs': 'export const a = 1;\n' }, './lib/e.mjs', { external: s => { seen.push(s); return true; } });
  assert.deepEqual(seen, []);
  assert.match(nested, /const \{ a \} = __lasm0;/);
  // Emscripten glue: spacing around the final export, exports and imports after whitespace.
  assert.equal(emscriptenModule('function M(){}export  default  M ;\n'), 'function M(){}\nexport default M;');
  for (const body of ['var a; export let z;', 'export  const x=1;'])
    assert.throws(() => emscriptenModule(`${body}function M(){}export default M;`), { message: 'Unexpected Emscripten glue: more than one export' }, body);
  for (const body of ['  import x from "y";', 'import  x from "y";', '}\nimport x from "y";'])
    assert.throws(() => emscriptenModule(`${body}function M(){}export default M;`), { message: 'Unexpected Emscripten glue: a static import' }, body);
});
