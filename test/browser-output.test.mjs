test('bundler: what it understands', async () => {
  const modules = {
    './entry.mjs': [
      "import { one as uno, gen } from './lib/a.mjs';",
      "import Klass from './lib/b.mjs';",
      "import { both } from './lib/d.mjs';",
      "import { x } from './lib/../lib/a.mjs'",
      'export const run = () => [uno, [...gen()], new Klass().k, both.c, both.d, x];',
    ].join('\n'),
    './lib/a.mjs': "export const one = 1;\nexport function* gen() { yield 2; }\nexport let x = 'x';\nexport var unused = 0;\nexport async function later() {}\n",
    './lib/b.mjs': "export default class { constructor() { this.k = 'k'; } }\n",
    './lib/d.mjs': 'import * as both from "../root/c.mjs";\nexport { both };\n',
    './root/c.mjs': "const c = 'c', dd = 'd';\nexport { c, dd as d };\nexport { c as default };\n",
  };
  const text = bundleModules(modules, './entry.mjs', { header: '// h' });
  assert.ok(text.startsWith('// h\nconst __lasm0 = (() => {\n'));
  assert.match(text, /return \{ one, gen, x, unused, later \};/);
  assert.match(text, /return \{ c, "d": dd, "default": c \};/);
  assert.match(text, /return \{ "default": __default \};/);
  assert.match(text, /const \{ one: uno, gen \} = __lasm0;/);
  assert.match(text, /const Klass = __lasm1\.default;/);
  assert.match(text, /const both = __lasm2;\n\nreturn \{ both \};/);
  assert.match(text, /const \{ both \} = __lasm3;/);
  assert.equal(text.match(/const __lasm\d = \(\(\) => \{/g).length, 4);
  const dir = mkdtempSync(join(tmpdir(), 'lasm-bundle-forms-'));
  try {
    writeFileSync(join(dir, 'b.mjs'), text);
    const { run } = await import(pathToFileURL(join(dir, 'b.mjs')).href);
    assert.deepEqual(run(), [1, [2], 'k', 'c', 'd', 'x']);
  } finally { rmSync(dir, { recursive: true, force: true }); }
  assert.equal(bundleModules({ './e.mjs': 'export const z = 1;\n' }, './e.mjs'), 'export const z = 1;\n');
  // Errors name the module and the line.
  assert.throws(() => bundleModules({ './e.mjs': "import './a.mjs';\n", './a.mjs': '' }, './e.mjs'), { message: "./e.mjs:1: unsupported import: import './a.mjs';" });
  assert.throws(() => bundleModules({ './e.mjs': "\nimport a, { b } from './a.mjs';\n", './a.mjs': '' }, './e.mjs'), { message: "./e.mjs:2: unsupported import: import a, { b } from './a.mjs';" });
  assert.throws(() => bundleModules({ './e.mjs': "import { a-b } from './a.mjs';\n", './a.mjs': '' }, './e.mjs'), { message: 'Unsupported binding a-b' });
  assert.throws(() => bundleModules({ './e.mjs': "import { a } from './a.mjs';\n", './a.mjs': "import { e } from './e.mjs';\nexport const a = 1;\n" }, './e.mjs'), { message: 'Cyclic import of ./e.mjs' });
  assert.throws(() => bundleModules({ './e.mjs': "import { a } from './a.mjs';\n", './a.mjs': "export * from './b.mjs';\n" }, './e.mjs'), { message: "./a.mjs:1: unsupported export: export * from './b.mjs';" });
  assert.throws(() => bundleModules({}, './e.mjs'), { message: 'The bundle has no module ./e.mjs' });
  assert.throws(() => bundleModules({ './e.mjs': "import x from 'pkg';\n" }, './e.mjs'), { message: './e.mjs: only relative imports can be bundled (pkg)' });
  assert.throws(() => bundleModules({ './e.mjs': "import x from '/abs.mjs';\n" }, './e.mjs'), /only relative imports/);
  // Dynamic imports and import.meta are left alone; a module imported twice is bundled once.
  const dynamic = bundleModules({ './e.mjs': "import { a } from './a.mjs';\nimport { b } from './a.mjs';\nconst m = import('./x.mjs');\nconst u = import.meta.url;\n", './a.mjs': 'export const a = 1, b = 2;\nexport const b2 = 3;\n' }, './e.mjs');
  assert.ok(dynamic.includes("const m = import('./x.mjs');\nconst u = import.meta.url;"));
  assert.equal(dynamic.match(/const __lasm0 = /g).length, 1);
  // Externals: one import each; relative imports are never external.
  const external = bundleModules({ './e.mjs': "import * as p from 'pkg';\nimport { q } from 'pkg';\nimport { r } from 'other';\nimport { s } from './s.mjs';\n", './s.mjs': 'export const s = 1;\n' },
    './e.mjs', { external: () => true });
  assert.equal(external.match(/^import \* as __lasmExternal\d from /gm).length, 2);
  assert.match(external, /^import \* as __lasmExternal0 from "pkg";\nimport \* as __lasmExternal1 from "other";$/m);
  assert.match(external, /const p = __lasmExternal0;\nconst \{ q \} = __lasmExternal0;\nconst \{ r \} = __lasmExternal1;\nconst \{ s \} = __lasm0;/);
  assert.throws(() => bundleModules({ './e.mjs': "import { s } from './s.mjs';\n" }, './e.mjs', { external: () => true }), /no module \.\/s\.mjs/);
});

test('compactModule and emscriptenModule', () => {
  assert.equal(compactModule('/* one */ a();\n/* two\n   lines */ b();\n/* three\n*/\n  // c\n\td();\n'), 'a();\nb();\nd();');
  assert.equal(compactModule('/** doc */\nx();\n/*\n*/'), 'x();');
  assert.equal(compactModule('a();\n/* open\nstill\n'), 'a();');
  const odd = 'const a = `x`; const b = `\n  // kept\n`;\n';
  assert.equal(compactModule(odd), odd);
  assert.equal(compactModule('const a = `x`;\n  b();\n'), 'const a = `x`;\nb();');
  assert.equal(emscriptenModule('function M(){}\nexport default M'), 'function M(){}\n\nexport default M;');
  assert.equal(emscriptenModule('var u=import.meta.url;var l=import("./x.js");function M(){}export default M;  \n'), 'var u=import.meta.url;var l=import("./x.js");function M(){}\nexport default M;');
  for (const body of ['export const x=1;', 'export function f(){}', 'export {a};', ';export class C{}', 'export async function g(){}', 'export let y;', 'export var z;', 'export default 1;'])
    assert.throws(() => emscriptenModule(`${body}function M(){}export default M;`), { message: 'Unexpected Emscripten glue: more than one export' }, body);
  for (const body of ['import "x";', 'import{a}from"x";', 'import*as a from"x";', "import a from 'x';", ';import x from"y";'])
    assert.throws(() => emscriptenModule(`${body}function M(){}export default M;`), { message: 'Unexpected Emscripten glue: a static import' }, body);
  assert.doesNotThrow(() => emscriptenModule('var reimport=1;var exported=2;function M(){}export default M;'));
  assert.throws(() => emscriptenModule('export default M; var x;'), { message: 'Unexpected Emscripten glue: no final export default' });
});

test('lasm package --target browser: every check and the _headers file', () => {
  const manifest = { entry: 'app.ba9876543210.js', wasm: 'app.0123456789ab.wasm', index: 'index.html', stableEntry: 'app.js' };
  assert.equal(headersFile(manifest), [
    '# Generated by Lasm (lasm package --target browser): caching and types for Netlify and Cloudflare Pages.',
    '/app.ba9876543210.js', '  Cache-Control: public, max-age=31536000, immutable',
    '/app.0123456789ab.wasm', '  Cache-Control: public, max-age=31536000, immutable', '  Content-Type: application/wasm',
    '/index.html', '  Cache-Control: no-cache', '/app.js', '  Cache-Control: no-cache', '/lasm-manifest.json', '  Cache-Control: no-cache'].join('\n') + '\n');
  const directory = mkdtempSync(join(tmpdir(), 'lasm-package-'));
  const logged = [];
  const log = line => logged.push(line);
  try {
    assert.throws(() => packageBrowser({ input: directory, log }), { message: `${directory} is not a browser build (no lasm-manifest.json); run lasm build Main.lean --target browser first` });
    const write = m => writeFileSync(join(directory, 'lasm-manifest.json'), JSON.stringify(m));
    write({ schema: 1, target: 'workers' });
    assert.throws(() => packageBrowser({ input: directory, log }), { message: `${join(directory, 'lasm-manifest.json')} is not a Lasm browser manifest` });
    write({ schema: 2, target: 'browser' });
    assert.throws(() => packageBrowser({ input: directory, log }), /is not a Lasm browser manifest/);
    const js = Buffer.from('export {};\n');
    const files = { [manifest.wasm]: { bytes: 8, sha256: sha256(wasmBytes), brotli: 1, gzip: 1 }, [manifest.entry]: { bytes: js.length, sha256: sha256(js), gzip: 1 }, 'index.html': { sha256: sha256(Buffer.from('<p>')) } };
    write({ ...manifest, schema: 1, target: 'browser', transfer: { brotli: 2048 }, files });
    assert.throws(() => packageBrowser({ input: directory, log }), { message: `${relative(process.cwd(), join(directory, manifest.wasm))} is missing` });
    writeFileSync(join(directory, manifest.wasm), wasmBytes);
    writeFileSync(join(directory, manifest.entry), js);
    writeFileSync(join(directory, 'index.html'), '<p>');
    assert.throws(() => packageBrowser({ input: directory, log }), { message: `${manifest.wasm}.br is missing or does not match ${manifest.wasm}` });
    writeFileSync(join(directory, manifest.wasm + '.br'), brotliCompressSync(Buffer.from('other')));
    assert.throws(() => packageBrowser({ input: directory, log }), { message: `${manifest.wasm}.br is missing or does not match ${manifest.wasm}` });
    writeFileSync(join(directory, manifest.wasm + '.br'), brotliCompressSync(wasmBytes));
    assert.throws(() => packageBrowser({ input: directory, log }), { message: `${manifest.wasm}.gz is missing or does not match ${manifest.wasm}` });
    writeFileSync(join(directory, manifest.wasm + '.gz'), gzipSync(wasmBytes));
    // The entry has a gzip copy only: no .br is needed.
    assert.throws(() => packageBrowser({ input: directory, log }), { message: `${manifest.entry}.gz is missing or does not match ${manifest.entry}` });
    writeFileSync(join(directory, manifest.entry + '.gz'), gzipSync(js));
    assert.equal(packageBrowser({ input: directory, log }), 0);
    assert.equal(readFileSync(join(directory, '_headers'), 'utf8'), headersFile(manifest));
    assert.equal(logged.at(-1), `Checked 3 files of ${relative(process.cwd(), directory) || directory} (2.0 KiB brotli); wrote _headers. Upload the directory to any static host: docs/deploy/browser.md`);
    // Our own _headers is rewritten; the user's is kept.
    writeFileSync(join(directory, '_headers'), '# Generated by Lasm (old)\n');
    packageBrowser({ input: directory, log });
    assert.equal(readFileSync(join(directory, '_headers'), 'utf8'), headersFile(manifest));
    writeFileSync(join(directory, '_headers'), '/*\n  X-Frame-Options: DENY\n');
    packageBrowser({ input: directory, log });
    assert.equal(readFileSync(join(directory, '_headers'), 'utf8'), '/*\n  X-Frame-Options: DENY\n');
    assert.equal(logged.at(-2), `[lasm] Kept your ${relative(process.cwd(), join(directory, '_headers'))}`);
    writeFileSync(join(directory, 'index.html'), '<p>changed');
    assert.throws(() => packageBrowser({ input: directory, log }), { message: 'index.html changed since lasm build (its SHA-256 differs from lasm-manifest.json)' });
  } finally { rmSync(directory, { recursive: true, force: true }); }
});

