const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const nodeNotices = 'THIRD-PARTY AND LASM NOTICES\n\n  - Lean 4.35.0 runtime and standard library (Apache-2.0)\n  - Emscripten 6.0.9\'s system libraries (MIT)\n\n=== Lasm ===\nMIT License\n';
const wasmBytes = Buffer.from([0, 97, 115, 109, 1, 0, 0, 0]);
const glue = 'async function Module(moduleArg={}){return new URL("program.wasm", import.meta.url).href}export default Module;';

/** A project with a Lean source, a Node build result and an edge program. */
function fixture({ packageJson, index, publicFiles } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'lasm-browser-out-'));
  const project = join(root, 'app');
  mkdirSync(project);
  writeFileSync(join(project, 'Main.lean'), 'def main : IO Unit := pure ()\n');
  if (packageJson) writeFileSync(join(project, 'package.json'), JSON.stringify(packageJson));
  if (index) writeFileSync(join(project, 'index.html'), index);
  if (publicFiles) for (const [file, text] of Object.entries(publicFiles)) { mkdirSync(join(project, 'public', file, '..'), { recursive: true }); writeFileSync(join(project, 'public', file), text); }
  const nodeOutput = join(root, 'node-out');
  mkdirSync(nodeOutput);
  writeFileSync(join(nodeOutput, 'THIRD_PARTY_NOTICES.txt'), nodeNotices);
  const programDirectory = join(root, 'program');
  mkdirSync(programDirectory);
  writeFileSync(join(programDirectory, 'program.wasm'), wasmBytes);
  writeFileSync(join(programDirectory, 'program.mjs'), glue);
  const args = (extra = {}) => ({
    source: join(project, 'Main.lean'), projectDirectory: project,
    result: { output: nodeOutput, jsBindings: [], profile: 'release', lean: '4.35.0', signature: 'node-signature' },
    program: { directory: programDirectory, meta: { suspend: 'jspi', key: 'program-key' } },
    log: () => {}, lasmVersion: '9.9.9', ...extra,
  });
  return { root, project, args };
}

test('browser output: files, names by content hash, precompressed copies and the manifest', async () => {
  const { root, project, args } = fixture({ packageJson: { name: '@me/shop' } });
  const logged = [];
  try {
    const { output, manifest } = writeBrowserOutput(args({ log: line => logged.push(line) }));
    assert.equal(output, join(project, 'dist'));
    const wasm = `app.${sha256(wasmBytes).slice(0, 12)}.wasm`;
    assert.equal(manifest.wasm, wasm);
    const bundle = readFileSync(join(output, manifest.entry));
    assert.equal(manifest.entry, `app.${sha256(bundle).slice(0, 12)}.js`);
    assert.deepEqual(readdirSync(output).sort(), [manifest.entry, manifest.entry + '.br', manifest.entry + '.gz', 'THIRD_PARTY_NOTICES.txt', 'app.js',
      wasm, wasm + '.br', wasm + '.gz', 'index.html', 'index.html.br', 'index.html.gz', 'lasm-manifest.json'].sort());
    assert.equal(existsSync(output + '.lasm-staging'), false);
    for (const file of [wasm, manifest.entry, 'index.html']) {
      const bytes = readFileSync(join(output, file));
      assert.deepEqual(brotliDecompressSync(readFileSync(join(output, file + '.br'))), bytes, file);
      assert.deepEqual(gunzipSync(readFileSync(join(output, file + '.gz'))), bytes, file);
      assert.deepEqual(manifest.files[file], { bytes: bytes.length, sha256: sha256(bytes), brotli: readFileSync(join(output, file + '.br')).length, gzip: readFileSync(join(output, file + '.gz')).length }, file);
    }
    assert.deepEqual(manifest.files['app.js'], { bytes: readFileSync(join(output, 'app.js')).length, sha256: sha256(readFileSync(join(output, 'app.js'))) });
    assert.deepEqual(readFileSync(join(output, wasm)), wasmBytes);
    assert.equal(readFileSync(join(output, 'app.js'), 'utf8'),
      `// Generated by Lasm (lasm build --target browser): a stable name for ${manifest.entry}; serve it with a short cache lifetime.\nexport * from './${manifest.entry}';\nexport { default } from './${manifest.entry}';\n`);
    assert.deepEqual({ ...manifest, files: undefined, entry: undefined }, {
      schema: 1, generator: 'lasm', target: 'browser', name: 'shop', lasm: '9.9.9', lean: '4.35.0', entry: undefined, wasm, stableEntry: 'app.js', index: 'index.html',
      notices: 'THIRD_PARTY_NOTICES.txt', suspend: 'none', modules: ['lasm:app'],
      immutable: [manifest.entry, wasm, manifest.entry + '.br', manifest.entry + '.gz', wasm + '.br', wasm + '.gz'],
      transfer: { brotli: manifest.files[wasm].brotli + manifest.files[manifest.entry].brotli, gzip: manifest.files[wasm].gzip + manifest.files[manifest.entry].gzip,
        uncompressed: wasmBytes.length + bundle.length },
      files: undefined, programKey: 'program-key', nodeBuildSignature: 'node-signature' });
    assert.deepEqual(JSON.parse(readFileSync(join(output, 'lasm-manifest.json'), 'utf8')), manifest);
    assert.ok(readFileSync(join(output, 'lasm-manifest.json'), 'utf8').endsWith('}\n'));
    assert.match(readFileSync(join(output, 'THIRD_PARTY_NOTICES.txt'), 'utf8'), /^THIRD-PARTY AND LASM NOTICES\n\nThis browser output was compiled by Lasm/);
    // The generated page names the app and loads the hashed files.
    const page = readFileSync(join(output, 'index.html'), 'utf8');
    assert.equal(page, defaultIndexHtml({ name: 'shop', entry: manifest.entry, wasm }));
    // The bundle: the legal banner, the glue's own Wasm URL made inert, the hashed Wasm URL.
    const text = bundle.toString();
    assert.ok(text.startsWith("// Generated by Lasm (lasm build --target browser): the shop app's loader, Lean runtime host and program glue. Do not edit.\n/*! The shop web app, built by Lasm."), text.slice(0, 300));
    assert.match(text, /Licence texts: THIRD_PARTY_NOTICES\.txt \*\/\n/);
    assert.ok(text.includes('return "program.wasm".href'));
    assert.ok(text.includes(`new URL("./${wasm}", import.meta.url)`));
    assert.equal(logged.length, 1);
    assert.match(logged[0], new RegExp(`^Built ${relative(process.cwd(), args().source).replace(/[.]/g, '\\.')} for the browser: ${relative(process.cwd(), output).replace(/[.]/g, '\\.')} \\(${manifest.entry.replace(/[.]/g, '\\.')} \\+ ${wasm.replace(/[.]/g, '\\.')}: \\d+\\.\\d KiB brotli, \\d+\\.\\d KiB gzip, \\d+\\.\\d KiB uncompressed\\)$`));

    // The same build again replaces Lasm's own output; a cached build says Reused.
    const again = writeBrowserOutput(args({ log: line => logged.push(line), cacheHit: true, suspend: 'jspi', lasmVersion: undefined }));
    assert.equal(again.manifest.suspend, 'jspi');
    assert.equal(again.manifest.lasm, null);
    assert.match(logged[1], /^Reused /);
    assert.match(readFileSync(join(output, again.manifest.entry), "utf8"), /const suspend = "jspi";/);
  } finally { rmSync(root, { recursive: true, force: true }); }
});

