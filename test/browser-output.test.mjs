// The browser build's files (src/browser/browser-build.mjs): writeBrowserOutput
// with a stand-in edge program (its glue and Wasm) and Node build result, the
// manifest, precompressed copies, public/, index.html, the output checks; the
// bundler's edge cases (src/browser/bundle.mjs); lasm package --target browser
// (src/browser/browser-package.mjs).
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
