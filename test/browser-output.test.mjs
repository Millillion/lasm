test('browser output: what it refuses', () => {
  const { root, project, args } = fixture({ packageJson: { lasm: { edge: { modules: ['left-pad', 'lasm:ui-dom'] } } } });
  try {
    assert.deepEqual(browserSuspendModes, ['none', 'jspi']);
    assert.throws(() => writeBrowserOutput(args({ suspend: 'asyncify' })), { message: '--suspend must be one of none, jspi' });
    assert.throws(() => writeBrowserOutput(args({ program: { ...args().program, meta: { suspend: 'none' } } })), { message: 'The browser build uses the JSPI-linked edge program (internal error)' });
    for (const output of [project, root])
      assert.throws(() => writeBrowserOutput(args({ output })), { message: 'The browser output directory must not contain the Lean sources' });
    // npm modules need a bundler.
    assert.throws(() => writeBrowserOutput(args({ output: join(root, 'o1') })), error =>
      error.message.startsWith('The program uses npm modules (left-pad), which a static browser build cannot resolve. Build it with Vite and the CLI\'s plugin, @lasm/cli/vite'));
    const kept = writeBrowserOutput(args({ output: join(root, 'o2'), externals: 'keep' }));
    assert.deepEqual(kept.manifest.modules, ['lasm:app', 'lasm:ui-dom', 'left-pad']);
    const bundle = readFileSync(join(root, 'o2', kept.manifest.entry), 'utf8');
    assert.match(bundle, /^import \* as __lasmExternal0 from "left-pad";$/m);
    assert.match(bundle, /Licence texts: THIRD_PARTY_NOTICES\.lasm\.txt \(emitted by the Lasm Vite plugin\) \*\//);
    // A directory that is not a browser build is not replaced; an empty one or our own is.
    const foreign = join(root, 'foreign');
    mkdirSync(foreign);
    writeFileSync(join(foreign, 'keep.txt'), 'mine');
    assert.throws(() => writeBrowserOutput(args({ output: foreign, externals: 'keep' })), /foreign|not.*Lasm|already/i);
    assert.equal(readFileSync(join(foreign, 'keep.txt'), 'utf8'), 'mine');
    writeFileSync(join(foreign, 'lasm-manifest.json'), JSON.stringify({ target: 'workers' }));
    assert.throws(() => writeBrowserOutput(args({ output: foreign, externals: 'keep' })));
    writeFileSync(join(foreign, 'lasm-manifest.json'), JSON.stringify({ target: 'browser' }));
    writeBrowserOutput(args({ output: foreign, externals: 'keep' }));
    assert.equal(existsSync(join(foreign, 'keep.txt')), false, 'our own output is replaced');
    const empty = join(root, 'empty');
    mkdirSync(empty);
    writeBrowserOutput(args({ output: empty, externals: 'keep' }));
    // The output must not be inside public/.
    mkdirSync(join(project, 'public'));
    assert.throws(() => writeBrowserOutput(args({ output: join(project, 'public', 'dist'), externals: 'keep' })), { message: 'The browser output directory must not be inside public/' });
    assert.deepEqual(readdirSync(join(project, 'public')), [], 'no staging directory is left in public/');
    assert.throws(() => writeBrowserOutput(args({ output: join(project, 'public'), externals: 'keep' })), { message: 'The browser output directory must not be inside public/' });
    // A project index.html that already loads a hashed loader, or has no </head>.
    writeFileSync(join(project, 'index.html'), '<html><body></body></html>');
    assert.throws(() => writeBrowserOutput(args({ output: join(root, 'o3'), externals: 'keep' })), /no <\/head>/);
  } finally { rmSync(root, { recursive: true, force: true }); }
});

